"""make_axis_test.py - writes axis_test.asm: one page of corners in X, in Y and in both, against the rest at the corner.

The corner test (corner_test) only flips the X speed (straight from the DAC). The Y speed comes from the Y hold
capacitor, loaded through the multiplexer, so a corner in Y can only be turned while the integrators are stopped:
here in one 16-bit store (STD to ORB + ORA: RAMP off, the multiplexer on with Y, the DAC = the new Y speed), the
restart in another (STX: RAMP on, the multiplexer off, the DAC = the X speed). Every sample: two line pieces of 16
cycles at speed $50, intensity $7F, a rest of N cycles between them (RAMP off to RAMP on, the beam on).

  row 1  X CORNERS: the X speed flips (-$50 -> +$50), the Y speed stays (-$50): "<", as the corner test.
         N = 0 (no stop), 5, 8, 12, 16, 24, 32, 48
  row 2  Y CORNERS: the Y speed flips (-$50 -> +$50), the X speed stays (+$50): "v".  N = 5, 8, 12, 16, 24, 32, 48, 64
  row 3  L CORNERS: X +$50 -> 0, Y 0 -> -$50 (both change).  N = 5, 8, 12, 16, 24, 32, 48, 64
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2, n
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

V, L = 0x50, 16
NX = [0, 5, 8, 12, 16, 24, 32, 48]
NY = [5, 8, 12, 16, 24, 32, 48, 64]
X0, DX = -0x6C, 0x1B
ROWS = [('X', 0x48, NX, (-V, -V), (V, -V)),          # (kind, y, rests, (vx1, vy1), (vx2, vy2))
        ('Y', 0x08, NY, (V, -V), (V, V)),
        ('L', -0x38, NY, (V, 0), (0, -V))]
LAB_DY = 0x14

def b8(v):
    return v & 0xFF

def load_y(vy):
    """the Y hold to vy (the integrators stopped)"""
    out = ['        lda     #$81', '        sta     <$00                ; ramp off, mux off',
           '        lda     #$%02X' % b8(vy), '        sta     <$01', '        lda     #$80',
           '        sta     <$00                ; mux on: Y speed into its hold']
    out += delay(8)
    out += ['        lda     #$81', '        sta     <$00                ; mux off']
    return out

def sample(kind, n, v1, v2):
    vx1, vy1 = v1; vx2, vy2 = v2
    out = load_y(vy1)
    out += ['        clr     <$0B                ; ACR: PB7 = RAMP and CB2 = /BLANK by hand']
    out += ['        ldy     #$01%02X' % b8(vx1), '        ldx     #$01%02X' % b8(vx2), '        lda     #$EE']
    out += ['        sty     <$00                ; ramp on, X speed: piece 1',
            '        sta     <$0C                ; beam on']
    if kind == 'X':
        out += ['        ldd     #$81%02X' % b8(vx2)]
        out += delay(L - 11)
        if n == 0:
            out += ['        stb     <$01                ; X speed: piece 2, no stop']
            out += delay(L - 6)
        else:
            out += ['        std     <$00                ; ramp off (+ X speed for piece 2)']
            out += delay(n - 5)
            out += ['        stx     <$00                ; ramp on: piece 2']
            out += delay(L - 6)
    else:
        out += ['        ldd     #$80%02X' % b8(vy2)]
        out += delay(L - 11)
        out += ['        std     <$00                ; ramp off, mux on: the DAC = the new Y speed into its hold']
        out += delay(n - 5)
        out += ['        stx     <$00                ; ramp on, mux off, the DAC = the X speed: piece 2']
        out += delay(L - 6)
    out += ['        lda     #$81', '        sta     <$00                ; ramp off',
            '        lda     #$CE', '        sta     <$0C                ; beam off',
            '        lda     #$98', '        sta     <$0B                ; ACR back for the BIOS']
    return out

A = []
w = A.append
w('; axis_test.asm - generated by make_axis_test.py: corners in X, in Y and in both, one page.')
w('; Build: lwasm --format=raw -o axis_test_raw.bin axis_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Moveto_d        equ $F312')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Vec_Text_HW     equ $C82A')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "AXIS TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('Main:')
w('        jsr     Wait_Recal')
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
for kind, y, ns, v1, v2 in ROWS:
    w('')
    w('; row %s' % kind)
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04                ; scale $7F for the moves')
    w('        ldd     #$%02X%02X' % (b8(y), b8(X0)))
    w('        jsr     Moveto_d')
    w('        lda     #$40')
    w('        sta     <$04                ; scale $40 for the moves between the samples')
    for i, n in enumerate(ns):
        w('; %s N = %d' % (kind, n))
        for s in sample(kind, n, v1, v2):
            w(s)
        if i < len(ns) - 1:
            ex = (v1[0] + v2[0]) * L / 64.0; ey = (v1[1] + v2[1]) * L / 64.0
            w('        ldd     #$%02X%02X' % (b8(-round(ey)), b8(round(DX * 2 - ex))))
            w('        jsr     Moveto_d            ; to the next sample')
w('')
w('        lda     #$5F')
w('        jsr     Intensity_a')
tw = int(round(0x36 * (DX / 3.0) / 7.5))
w('        ldd     #$F8%02X' % tw)
w('        std     Vec_Text_HW')
for kind, y, ns, v1, v2 in ROWS:
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        sta     <$04')
    w('        ldu     #Lab%s' % kind)
    w('        ldd     #$%02X%02X' % (b8(y + LAB_DY), b8(X0 - 4)))
    w('        jsr     Print_Str_d')
w('        lbra    Main')
w('')
for kind, y, ns, v1, v2 in ROWS:
    w('Lab%s    fcc     "%s"' % (kind, ''.join('%-3d' % n for n in ns).rstrip()))
    w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'axis_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote axis_test.asm')
