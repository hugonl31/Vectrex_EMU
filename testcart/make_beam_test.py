"""make_beam_test.py - writes beam_test.asm: four pages about the beam's analog path, one photo each.
Buttons 1-4 (controller 1) pick the page; the page number and name are shown at the top.

  page 1  ZERO OFFSET. Where does ZERO take the beam when the integrators' offset (the zero reference, mux 1) is
          not 0? (Malban 2026: to a point on the diagonal, offset $50 = lower left.) Per offset: zero for ~400
          cycles with the offset set, then a BIG dot (40 cycles) there; then the offset back to 0 (RAMP off) and a
          SMALL dot (8 cycles): does the beam stay or jump? Offsets in order, the big dots growing:
          $00 $10 $20 $30 $40 $50 $E0(-$20) $C0(-$40) - big dot 12, 16, 20 ... 40 cycles.
          Then two lines drawn by the offset alone (X and Y speed 0, RAMP on 96 cycles, offset $20 and $E0): does
          the offset move the beam while RAMP is on? A frame (+-$60 at scale $7F) gives the scale.
  page 2  ZEROING. Four lit ZERO sweeps (intensity $3F) from the frame's corners: the path's shape and, from its
          brightness, the speed. Then the partial zeros: from 10 start points (left, at different heights, each
          marked with a small dot) ZERO for N cycles (dark), then a dot (16 cycles) where the beam got to.
          N from the top start: 4 6 8 10 12 16 20 24 32 48.
  page 3  DAC SLANT A. The same string at text widths 60..66 (the BIOS text routine, each row from zero):
          the slant per width (the DAC's bit errors: Malban, PrintStr (3) - DAC). No title (the frame time).
  page 4  DAC SLANT B. Widths 52 56 58 67 68 72 76.
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2, n
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

def b8(v):
    return v & 0xFF

_lab = [0]
def wait_long(n5):
    """~5 * n5 cycles (not exact)"""
    _lab[0] += 1; l = 'Wl%d' % _lab[0]
    return ['        ldb     #%d' % n5, '%-7s decb' % l, '        bne     %s' % l]

def set_offset(o):
    """the integrators' offset (the zero reference, mux 1) to o; RAMP stays off (ACR = 0: PB7 by hand)"""
    return ['        lda     #$%02X' % b8(o), '        sta     <$01                ; DAC = offset',
            '        lda     #$82', '        sta     <$00                ; ramp off, mux on: 1 (the offset)'] + delay(10) + \
           ['        lda     #$83', '        sta     <$00                ; mux off', '        clr     <$01']

def set_y(v):
    return ['        lda     #$%02X' % b8(v), '        sta     <$01',
            '        lda     #$80', '        sta     <$00                ; ramp off, mux on: 0 (the Y hold)'] + delay(10) + \
           ['        lda     #$81', '        sta     <$00                ; mux off', '        clr     <$01']

def dot(n):
    """the beam on for n cycles (n = 4 or >= 6), RAMP off: a dot where the beam is"""
    return ['        ldd     #$EECE', '        sta     <$0C                ; beam on'] + delay(n - 4) + \
           ['        stb     <$0C                ; beam off']

def manual(on):
    return ['        clr     <$0B                ; ACR: PB7 = RAMP and CB2 = /BLANK by hand'] if on else \
           ['        lda     #$98', '        sta     <$0B                ; ACR back for the BIOS']

def reset_and_move(y, x, scale=0x7F):
    return ['        jsr     Reset0Ref', '        lda     #$%02X' % scale, '        sta     <$04',
            '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Moveto_d']

A = []
w = A.append
def ws(lines):
    for s in lines: w(s)

w('; beam_test.asm - generated by make_beam_test.py: ZERO, the integrators\' offset, zeroing and the DAC.')
w('; Build: lwasm --format=raw -o beam_test_raw.bin beam_test.asm, then pad to 32768 bytes with $FF.')
w('')
for name, adr in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Moveto_d', 0xF312),
                  ('Reset0Ref', 0xF354), ('Print_Str_d', 0xF37A), ('Draw_Line_d', 0xF3DF)):
    w('%-15s equ $%04X' % (name, adr))
w('Vec_Text_HW     equ $C82A')
w('Vec_Buttons     equ $C811')
w('Page            equ $C880')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "BEAM TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('        clr     Page')
w('Main:')
w('        jsr     Wait_Recal')
w('        jsr     Read_Btns')
w('        lda     Vec_Buttons')
for k in range(4):
    w('        bita    #%d' % (1 << k))
    w('        beq     Bt%d' % k)
    w('        ldb     #%d' % k)
    w('        stb     Page')
    w('Bt%d' % k)
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
w('        lda     Page')
w('        lbeq    Page1')
w('        deca')
w('        lbeq    Page2')
w('        deca')
w('        lbeq    Page3')
w('        lbra    Page4')
w('')

def title(lbl):
    ws(['        lda     #$5F', '        jsr     Intensity_a', '        ldd     #$F850', '        std     Vec_Text_HW'])
    ws(reset_and_move(0, 0))
    ws(['        ldu     #%s' % lbl, '        ldd     #$70%02X' % b8(-0x60), '        jsr     Print_Str_d'])

def frame():
    """a square +-$60 at scale $7F (the scale for the photo)"""
    ws(['        lda     #$3F', '        jsr     Intensity_a'])
    ws(reset_and_move(-0x60, -0x60))
    for dy, dx in ((0x7F, 0), (0x41, 0), (0, 0x7F), (0, 0x41), (-0x7F, 0), (-0x41, 0), (0, -0x7F), (0, -0x41)):
        ws(['        ldd     #$%02X%02X' % (b8(dy), b8(dx)), '        jsr     Draw_Line_d'])

# ---- page 1: ZERO with an offset
w('Page1:')
title('T1')
frame()
OFS = [0x00, 0x10, 0x20, 0x30, 0x40, 0x50, -0x20, -0x40]
ws(['        lda     #$7F', '        jsr     Intensity_a'])
for i, o in enumerate(OFS):
    w('; offset %d' % o)
    ws(['        jsr     Reset0Ref'])
    ws(manual(True))
    ws(set_offset(o))
    ws(['        lda     #$CC', '        sta     <$0C                ; ZERO on (beam off)'])
    ws(wait_long(80))
    ws(['        lda     #$CE', '        sta     <$0C                ; ZERO off'])
    ws(dot(12 + 4 * i))
    ws(set_offset(0))
    ws(dot(8))
    ws(manual(False))
for o in (0x20, -0x20):
    w('; a line by the offset alone: %d' % o)
    ws(['        jsr     Reset0Ref'])
    ws(manual(True))
    ws(set_y(0))
    ws(set_offset(o))
    ws(['        ldd     #$EE01', '        sta     <$0C                ; beam on', '        stb     <$00                ; ramp on (X = DAC = 0, Y = 0)'])
    ws(wait_long(19))
    ws(['        lda     #$81', '        sta     <$00                ; ramp off', '        lda     #$CE', '        sta     <$0C                ; beam off'])
    ws(set_offset(0))
    ws(manual(False))
w('        lbra    Main')
w('')

# ---- page 2: zeroing
w('Page2:')
title('T2')
frame()
ws(['        lda     #$3F', '        jsr     Intensity_a'])
for y, x in ((0x60, 0x60), (0x60, -0x60), (-0x60, 0x60), (-0x60, -0x60)):
    w('; a lit sweep from (%d, %d)' % (y, x))
    ws(reset_and_move(y, x))
    ws(manual(True))
    ws(['        lda     #$EC', '        sta     <$0C                ; ZERO on, beam on'])
    ws(wait_long(16))
    ws(['        lda     #$CE', '        sta     <$0C                ; ZERO off, beam off'])
    ws(manual(False))
ws(['        lda     #$7F', '        jsr     Intensity_a'])
NZ = [4, 6, 8, 10, 12, 16, 20, 24, 32, 48]
for i, n in enumerate(NZ):
    y = 0x5A - i * 0x14
    w('; partial zero N = %d from (%d, -$70)' % (n, y))
    ws(reset_and_move(y, -0x70))
    ws(manual(True))
    ws(dot(6))
    ws(['        ldd     #$CCCE', '        sta     <$0C                ; ZERO on'] + delay(n - 4) +
       ['        stb     <$0C                ; ZERO off'])
    ws(dot(16))
    ws(manual(False))
w('        lbra    Main')
w('')

# ---- pages 3, 4: the DAC
def dac_page(lbl, widths, tlbl):
    """(no title: the frame time - each row ~4,500 cycles; the widths say which page)"""
    ws(['        lda     #$7F', '        jsr     Intensity_a'])
    for i, wd in enumerate(widths):
        y = 0x48 - i * 0x16
        ws(['        ldd     #$F8%02X' % wd, '        std     Vec_Text_HW'])
        ws(['        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04'])
        ws(['        ldu     #%s%d' % (lbl, i), '        ldd     #$%02X%02X' % (b8(y), b8(-0x78)), '        jsr     Print_Str_d'])
    w('        lbra    Main')

W3 = [60, 61, 62, 63, 64, 65, 66]
W4 = [52, 56, 58, 67, 68, 72, 76]
w('Page3:')
dac_page('S3_', W3, 'T3')
w('')
w('Page4:')
dac_page('S4_', W4, 'T4')
w('')
w('T1      fcc     "1 ZERO OFFSET"')
w('        fcb     $80')
w('T2      fcc     "2 ZEROING"')
w('        fcb     $80')
w('T3      fcc     "3 DAC A"')
w('        fcb     $80')
w('T4      fcc     "4 DAC B"')
w('        fcb     $80')
for lbl, ws_ in (('S3_', W3), ('S4_', W4)):
    for i, wd in enumerate(ws_):
        w('%s%d    fcc     "%d IIIIIIII"' % (lbl, i, wd))
        w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'beam_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote beam_test.asm')
