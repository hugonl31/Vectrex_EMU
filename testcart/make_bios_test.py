"""make_bios_test.py - writes bios_test.asm ("BIOS TIMING"): the shift register's and timer 1's fine print, and X with
Y. Buttons 1-4; 50 Hz; every write on its cycle.

Page 1  SR GAP    RAMP on by hand for 100 cycles (speed $7F); the shift register $FF written at cycle 30 and $00 written
                  G cycles later, G = 10 .. 24 one a row (top to bottom), $00 again 24 cycles after that. Where the first
                  $00 does not blank (the Join Test: 17 cycles after the $FF) the dash runs on to the second.
Page 2  SR BYTE   the same line; one byte written once at cycle 30 (rows: $80, $C0, $F0, $AA, $CC, $0F, $55, $01), $00 at
                  cycle 70: the eight bits as the tube shows them - their order, their length, what stays on after them.
Page 3  T1 FLAG   timer 1 started (N = 6 .. 20, one a row), the BIOS's wait loop (BITA <$0D / BEQ: 7 cycles a pass), then
                  the beam off by PCR at once: the line's end steps as the loop catches the flag a pass later - where it
                  steps says when the flag comes up.
Page 4  X AND Y   eight rays of 30 cycles (speed $50 along, every 45 degrees) from one point: left star with the X speed
                  in the DAC before RAMP on (as the BIOS), right star with it written together with RAMP on (as my carts).
                  A ray that starts bent: one axis starts before the other.
"""
import make_dot_test as D
from tc_common import *
from make_switch_test import Sched, STX, STY, STAC, STBC
from make_settle_test import run
from make_timer_test import STASR, STBSR, STT1

GAPS = list(range(10, 25))
BYTES = [0x80, 0xC0, 0xF0, 0xAA, 0xCC, 0x0F, 0x55, 0x01]
T1N = list(range(6, 21))
X0 = -0x60

def sr_setup(v):
    w('        lda     #$81'); w('        sta     <$00                ; ramp off, mux off')
    w('        lda     #$18'); w('        sta     <$0B                ; ACR: RAMP by hand, /BLANK = the shift register')
    w('        clr     <$0A                ; the shift register 0')
    set_y(0)
    w('        ldx     #$01%02X' % v); w('        ldy     #$81%02X' % v)

def sr_gap(g):
    sr_setup(0x7F); w('        lda     #$FF'); w('        clrb')
    run([(10, STX), (30, STASR), (30 + g, STBSR), (54 + g, STBSR), (110, STY)]); hand_off()

def sr_byte(b):
    sr_setup(0x7F); w('        lda     #$%02X' % b); w('        clrb')
    run([(10, STX), (30, STASR), (70, STBSR), (110, STY)]); hand_off()

def t1_flag(N):
    w('        lda     #$81'); w('        sta     <$00                ; mux off')
    w('        lda     #$80'); w('        sta     <$0B                ; ACR: PB7 = timer 1, /BLANK by PCR')
    set_y(0)
    w('        lda     #$7F'); w('        sta     <$01                ; the X speed'); w('        lda     #$%02X' % N); w('        sta     <$04                ; timer 1: %d cycles' % N)
    w('        lda     #$EE'); w('        ldb     #$CE')
    s = Sched(); s.write(*STAC, 8)
    s.op('lda     #$40', 2); s.write(*STT1, 20)                              # the timer starts (the write in cycle 20)
    w('        bita    <$0D                ; the wait loop: timer 1\'s flag (the read in cycles 24, 31, 38 ...)'.replace("\\'", "'"))
    w('        beq     *-2')
    w('        stb     <$0C                ; beam off, 7 cycles after the read that saw the flag')
    w('        clr     <$01'); hand_off()

def ray(vx, vy, early):
    """30 cycles at (vx, vy); early: the X speed in the DAC before RAMP on (a port-B write), else with it (STX)"""
    hand_on(); set_y(vy)
    w('        lda     #$EE'); w('        ldb     #$CE')
    if early:
        w('        ldx     #$81%02X' % b8(vx)); w('        stx     <$00                ; mux off, the DAC: the X speed')
        w('        ldx     #$01%02X' % b8(vx)); w('        ldy     #$81%02X' % b8(vx))
        for s_ in delay(12): w(s_)
    else:
        w('        clr     <$01                ; the DAC 0'); w('        ldx     #$01%02X' % b8(vx)); w('        ldy     #$81%02X' % b8(vx))
    run([(8, STAC), (20, STX), (50, STY), (90, STBC)]); w('        clr     <$01'); hand_off()

def build():
    begin('BIOS TIMING', 'bios_test.asm - generated by make_bios_test.py: the shift register, timer 1\'s flag, X with Y; buttons 1-4.'.replace("\\'", "'"))
    page(1)
    for i, g in enumerate(GAPS):
        w('; SR gap %d' % g); row_start(0x7F, 0x60 - i * 0x0C, X0); sr_gap(g)
    text('L1', 0x70, -0x70); text('T1', -0x74, -0x50); page_end()
    page(2)
    for i, b in enumerate(BYTES):
        w('; SR byte $%02X' % b); row_start(0x7F, 0x58 - i * 0x14, X0); sr_byte(b)
    text('L2', 0x70, -0x70); text('T2', -0x74, -0x50); page_end()
    page(3)
    for i, N in enumerate(T1N):
        w('; timer 1 N = %d, the wait loop, beam off' % N); row_start(0x7F, 0x60 - i * 0x0C, X0); t1_flag(N)
    text('L3', 0x70, -0x70); text('T3', -0x74, -0x50); page_end()
    page(4)
    V = 0x50; D45 = 0x39
    for early, cx in ((True, -0x38), (False, 0x38)):
        for vx, vy in ((V, 0), (D45, D45), (0, V), (-D45, D45), (-V, 0), (-D45, -D45), (0, -V), (D45, -D45)):
            w('; ray %d %d, the X speed %s' % (vx, vy, 'before RAMP on' if early else 'with RAMP on')); row_start(0x7F, 0x10, cx); ray(vx, vy, early)
    text('L4', 0x70, -0x70); text('T4', -0x74, -0x50); page_end()
    w('')
    string('L1', 'SR OFF AFTER 10 TO 24'); string('T1', '1 SR GAP')
    string('L2', 'SR 80 C0 F0 AA CC 0F 55 01'); string('T2', '2 SR BYTE')
    string('L3', 'TIMER 6 TO 20  WAIT LOOP'); string('T3', '3 T1 FLAG')
    string('L4', 'X BEFORE RAMP   X WITH RAMP'); string('T4', '4 X AND Y')
    finish('bios_test', 'BIOS Timing')

if __name__ == '__main__':
    build()
