"""make_bright_test.py - writes bright_test.asm: one page of the beam's brightness against its intensity.

16 columns, intensity $02..$7F (dense at the low end, where the beam nears cutoff). Each column: a
vertical bar drawn with the BIOS line routine (the same speed and length for all), a dot below it (the
same resting time for all), the intensity in hex at the bottom. Photographed with a fixed exposure, the
bars' and dots' brightness per intensity calibrates the emulator's brightness curve (vecrender.beam_z).
"""
import os

LEVELS = [0x02, 0x04, 0x08, 0x0C, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38, 0x40, 0x50, 0x60, 0x70, 0x78, 0x7F]
XS = [-0x70 + 0x0F * k for k in range(len(LEVELS))]
BAR_TOP, BAR_LEN, DOT_Y, LAB_Y1, LAB_Y2 = 0x50, 0x48, -0x14, -0x38, -0x48
TEXT_W, LAB_DX = int(__import__('os').environ.get('BT_W', '0x36'), 16), int(__import__('os').environ.get('BT_DX', '-11'))

A = []
w = A.append
w('; bright_test.asm - generated by make_bright_test.py: brightness against intensity, one page.')
w('; Build: lwasm --format=raw -o bright_test_raw.bin bright_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Dot_here        equ $F2C5')
w('Moveto_d        equ $F312')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Draw_Line_d     equ $F3DF')
w('Vec_Dot_Dwell   equ $C828')
w('Vec_Text_HW     equ $C82A')
w('VIA_t1_cnt_lo   equ $D004')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "BRIGHTNESS"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('Main:')
w('        jsr     Wait_Recal')
w('        lda     #$10')
w('        sta     Vec_Dot_Dwell')
for z, x in zip(LEVELS, XS):
    w('        jsr     Reset0Ref           ; intensity $%02X: the bar' % z)
    w('        lda     #$%02X' % z)
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     VIA_t1_cnt_lo')
    w('        ldd     #$%04X' % (((BAR_TOP & 0xff) << 8) | (x & 0xff)))
    w('        jsr     Moveto_d')
    w('        ldd     #$%04X' % (((-BAR_LEN) & 0xff) << 8))
    w('        jsr     Draw_Line_d')
    w('        ldd     #$%04X              ; the dot: from the end of the bar' % (((DOT_Y - (BAR_TOP - BAR_LEN)) & 0xff) << 8))
    w('        jsr     Moveto_d')
    w('        jsr     Dot_here')
w('        lda     #$7F')                       # the labels: two strings, alternate columns (text is slow)
w('        jsr     Intensity_a')
w('        ldd     #$F8%02X' % TEXT_W)
w('        std     Vec_Text_HW')
for row, y in ((0, LAB_Y1), (1, LAB_Y2)):
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        sta     VIA_t1_cnt_lo')
    w('        ldu     #Labs%d' % row)
    w('        ldd     #$%04X' % (((y & 0xff) << 8) | ((XS[row] + LAB_DX) & 0xff)))
    w('        jsr     Print_Str_d')
w('        lbra    Main')
w('')
for row in (0, 1):
    w('Labs%d   fcc     "%s"' % (row, '  '.join('%02X' % z for z in LEVELS[row::2])))
    w('        fcb     $80')

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bright_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote bright_test.asm')
