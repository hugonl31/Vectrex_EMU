"""make_corner_test.py - writes corner_test.asm: one page measuring the light of a beam that stops for a moment.

Where a vector ends and the next one starts, the beam rests a few cycles with the integrators stopped (RAMP
off) but the beam on: games show "corner dots" there. How bright and how big they are on a real tube decides
the emulator's corner dots (vecrender BEAM_DOTMAX, the halo, the bloom).

Each sample is drawn cycle-exact with the VIA (not the BIOS line routine): two short line pieces (speed $50,
like Vectorblade's lines) with a rest of N cycles between them, the beam on throughout. Columns: N = 0 (the
pieces run straight on), 5, 8, 12, 16, 24, 32, 48, 64, 96 cycles (labelled at the top). Rows, top to bottom:
  1-4  STRAIGHT at intensity $7F, $5F, $3F, $2F: the second piece continues the first (the rest is the only
       difference between the columns)
  5-6  CORNER at $7F, $5F: a 90 degree corner (the X speed flips, the Y speed stays), as in a game's shape
  7    DOT at $7F: the beam on for N cycles without moving (no lines)
RAMP and the X speed change in one 16-bit store (STD / STY to ORB + ORA), so even short rests are exact.
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2, n
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

NS = [0, 5, 8, 12, 16, 24, 32, 48, 64, 96]          # the rest, cycles (STD's ORB write to STY's ORB write)
X0, DX = -0x6C, 0x17                                # the columns: the first sample's start, the spacing (units, scale $7F)
V, L = 0x50, 16                                     # the line speed (DAC) and each piece's length (cycles)
ROWS = [('S', 0x7F, 0x50), ('S', 0x5F, 0x3A), ('S', 0x3F, 0x24), ('S', 0x2F, 0x0E),
        ('C', 0x7F, -0x0C), ('C', 0x5F, -0x30), ('D', 0x7F, -0x58)]
LAB_Y = 0x68
TEXT_W, LAB_DX = int(os.environ.get('CT_W', '0x36'), 16), int(os.environ.get('CT_DX', '-4'))
SEG1_FIX = 13                                       # STX (ramp on) .. STD (ramp off): 2 + 4 + 3 + delay + 4
SEG2_FIX = 5                                        # STY (ramp on) .. STD (ramp off): delay + 5

def b8(v):
    return v & 0xFF

A = []
w = A.append
w('; corner_test.asm - generated by make_corner_test.py: the light of a resting beam (corner dots), one page.')
w('; Build: lwasm --format=raw -o corner_test_raw.bin corner_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Moveto_d        equ $F312')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Vec_Text_HW     equ $C82A')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "CORNER TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('Main:')
w('        jsr     Wait_Recal')
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
for kind, z, y in ROWS:
    w('')
    w('; row: %s at intensity $%02X' % ({'S': 'straight', 'C': 'corner', 'D': 'dot'}[kind], z))
    w('        jsr     Reset0Ref')
    w('        lda     #$%02X' % z)
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04                ; scale $7F for the moves')
    w('        ldd     #$%02X%02X' % (b8(y), b8(X0)))
    w('        jsr     Moveto_d')
    w('        lda     #$40')
    w('        sta     <$04                ; scale $40 for the short moves between the samples')
    if kind == 'S':
        vy, vx1, vx2 = 0, V, V
    elif kind == 'C':
        vy, vx1, vx2 = -V, -V, V                   # down-left, then down-right
    for i, n in enumerate(NS):
        w('; N = %d' % n)
        w('        lda     #$81')
        w('        sta     <$00                ; ramp off, mux off')
        w('        clr     <$0B                ; ACR: PB7 = RAMP and CB2 = /BLANK by hand (no timer, no shift register)')
        if kind == 'D':
            if n:
                w('        lda     #$EE')
                w('        ldb     #$CE')
                w('        sta     <$0C                ; beam on')
                for s in delay(n - 4 if n != 5 else 2):    # (5 cannot be: 6)
                    w(s)
                w('        stb     <$0C                ; beam off: %d cycles' % (n if n != 5 else 6))
            dx, dy = DX * 2, 0
        else:
            w('        lda     #$%02X' % b8(vy))
            w('        sta     <$01')
            w('        lda     #$80')
            w('        sta     <$00                ; mux on: Y speed into its hold')
            for s in delay(8):
                w(s)
            w('        lda     #$81')
            w('        sta     <$00                ; mux off')
            w('        ldx     #$01%02X' % b8(vx1))
            w('        ldy     #$01%02X' % b8(vx2))
            w('        stx     <$00                ; ramp on, X speed: piece 1')
            w('        lda     #$EE')
            w('        sta     <$0C                ; beam on')
            w('        ldd     #$81%02X' % b8(vx2))
            for s in delay(L - SEG1_FIX):
                w(s)
            if n == 0:
                w('        stb     <$01                ; X speed: piece 2, no stop')
                for s in delay(L - 4):
                    w(s)
            else:
                w('        std     <$00                ; ramp off (+ X speed for piece 2)')
                for s in delay(n - 5 if n > 5 else 0):
                    w(s)
                w('        sty     <$00                ; ramp on: piece 2')
                for s in delay(L - SEG2_FIX):
                    w(s)
            w('        std     <$00                ; ramp off')
            w('        lda     #$CE')
            w('        sta     <$0C                ; beam off')
            # where the beam is now, from the sample's start (units at scale $7F: DAC x cycles / 127)
            ex = (vx1 * L + vx2 * L) / 64.0                 # (in units at scale $40)
            ey = (vy * 2 * L) / 64.0
            dx, dy = DX * 2 - round(ex), -round(ey)
        w('        lda     #$98')
        w('        sta     <$0B                ; ACR back for the BIOS')
        if i < len(NS) - 1:
            w('        ldd     #$%02X%02X' % (b8(dy), b8(dx)))
            w('        jsr     Moveto_d            ; to the next sample')
# the labels: N above each column
w('')
w('        lda     #$5F')
w('        jsr     Intensity_a')
w('        ldd     #$F8%02X' % TEXT_W)
w('        std     Vec_Text_HW')
w('        jsr     Reset0Ref')
w('        lda     #$7F')
w('        sta     <$04')
w('        ldu     #Labs')
w('        ldd     #$%02X%02X' % (b8(LAB_Y), b8(X0 + LAB_DX)))
w('        jsr     Print_Str_d')
w('        lbra    Main')
w('')
w('Labs    fcc     "%s"' % ''.join('%-3d' % n for n in NS).rstrip())     # (3 characters a column: one column = DX)
w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'corner_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote corner_test.asm')
