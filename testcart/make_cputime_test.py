"""make_cputime_test.py - writes cputime_test.asm: one static page of CPU and VIA timing numbers.

Left column: cycles of 6809 instructions, timed with VIA timer 2 (a routine with the instruction minus
an empty routine). Right column: raw VIA readings at exact cycle offsets after a timer 1 start or a
shift register write (timer 1 counter, its interrupt flag, PB7 = the ramp switch, the shift register's
flag). Run once at power-on; the page shows the results in hex. Compare a photo of the real Vectrex
with the emulator (roms\\CPU Timing Test.bin).
"""
import os

def delay(n):
    """exactly n cycles (n >= 2): NOP = 2, BRN = 3"""
    assert n >= 2
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

# left: (label, routine body)
INST = [
    ('NOP',      ['nop']),
    ('MUL',      ['mul']),
    ('PSH PUL',  ['pshs    cc,a,b,dp,x,y,u', 'puls    cc,a,b,dp,x,y,u']),
    ('LDA ,X',   ['lda     ,x']),
    ('LDA 1,X',  ['lda     1,x']),
    ('LDA ,X+',  ['lda     ,x+']),
    ('LDA [,X]', ['lda     [,x]']),
    ('LDA D,X',  ['lda     d,x']),
    ('LDA A,X',  ['lda     a,x']),
    ('LBRA',     ['lbra    @t', '@t']),
    ('CLR LBEQ', ['clra', 'lbeq    @t', '@t']),
    ('LD1 LBEQ', ['lda     #1', 'lbeq    @t', '@t']),
    ('JSR RTS',  ['jsr     Sub']),
    ('EXG X,Y',  ['exg     x,y']),
    ('TFR X,Y',  ['tfr     x,y']),
    ('LEAX 1,X', ['leax    1,x']),
]
# right: (label, code) - each leaves the byte to show in A
VIA = []
VIA.append(('T1 RD 0', ['lda     #$40', 'sta     $D004', 'ldb     #0', 'stb     $D005', 'lda     $D004']))
VIA.append(('T1 RD 2', ['lda     #$40', 'sta     $D004', 'ldb     #0', 'stb     $D005', 'nop', 'lda     $D004']))
VIA.append(('T1 WRAP', ['lda     #$04', 'sta     $D004', 'ldb     #0', 'stb     $D005'] + [l.strip() for l in delay(20)] + ['lda     $D004']))
for off in range(16, 20):       # timer 1 = 16: its flag, read in the last cycle of an LDA (5 cycles) after `off - 5` cycles
    VIA.append(('T1F %d' % off, ['lda     #$10', 'sta     $D004', 'ldb     #0', 'stb     $D005'] + [l.strip() for l in delay(off - 5)] + ['lda     $D00D', 'anda    #$40']))
for off in range(17, 20):       # PB7 (timer 1 drives it: low while running)
    VIA.append(('PB7 %d' % off, ['lda     #$10', 'sta     $D004', 'ldb     #0', 'stb     $D005'] + [l.strip() for l in delay(off - 5)] + ['lda     $D000', 'anda    #$80']))
for off in range(13, 19):       # shift register: 8 bits out under the system clock, its flag
    VIA.append(('SRF %d' % off, ['lda     #$FF', 'sta     $D00A'] + [l.strip() for l in delay(off - 5)] + ['lda     $D00D', 'anda    #$04']))
assert len(INST) == 16 and len(VIA) == 16

ROWLEN = 26                       # a row: its letter, 8 x (space + 2 hex digits), $80
A = []
w = A.append
w('; cputime_test.asm - generated by make_cputime_test.py: 6809 instruction cycles and VIA timing, one page.')
w('; Build: lwasm --format=raw -o cputime_test_raw.bin cputime_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Vec_Text_HW     equ $C82A')
w('VIA_t1_cnt_lo   equ $D004')
w('')
w('Vals            equ $C880           ; 32 results')
w('RowBuf          equ $C980           ; the 16 rows as strings, %d bytes each' % ROWLEN)
w('Buf             equ $C900           ; the indexed tests\' data (a pointer to itself at $C900)')
w('Idx             equ $C8F0')
w('PosY            equ $C8F1')
w('Base            equ $C8F2')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "CPU TIMING"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('        ldd     #Buf')
w('        std     Buf                 ; ([,X] reads through it)')
w('        ldy     #T_base')
w('        jsr     Meas')
w('        stb     Base')
for i in range(16):
    w('        ldy     #T_i%d' % i)
    w('        jsr     Meas')
    w('        negb')
    w('        addb    Base')
    w('        stb     Vals+%d' % i)
for i in range(16):
    w('        jsr     T_v%d' % i)
    w('        sta     Vals+%d' % (16 + i))
w('        jsr     MakeRows')
w('')
w('Main:')
w('        jsr     Wait_Recal')
w('        ldd     #$F838')
w('        std     Vec_Text_HW')
w('        lda     #$7F')
w('        jsr     Intensity_a')
rows = [('RowBuf+%d' % (ROWLEN * r), 0x20 - 0x20 * r, -0x6C) for r in range(4)]
for addr, y, x in rows:         # one string per row: few BIOS calls (the page at 50 Hz)
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        sta     VIA_t1_cnt_lo')
    w('        ldu     #%s' % addr)
    w('        ldd     #$%04X' % (((y & 0xff) << 8) | (x & 0xff)))
    w('        jsr     Print_Str_d')
w('        jmp     Main')
w('')
w('; MakeRows - the row templates to RAM, the values into them in hex')
w('MakeRows:')
w('        ldx     #RowTpl')
w('        ldu     #RowBuf')
w('        ldy     #%d' % (4 * ROWLEN))
w('@c      lda     ,x+')
w('        sta     ,u+')
w('        leay    -1,y')
w('        bne     @c')
for k in range(32):
    r, off = k // 8, 2 + 3 * (k % 8)
    w('        ldu     #RowBuf+%d' % (ROWLEN * r + off))
    w('        lda     Vals+%d' % k)
    w('        jsr     PutHex')
w('        rts')
w('')
w('PutHex:')
w('        pshs    a')
w('        lsra')
w('        lsra')
w('        lsra')
w('        lsra')
w('        jsr     Nib')
w('        sta     ,u+')
w('        puls    a')
w('        anda    #$0F')
w('        jsr     Nib')
w('        sta     ,u')
w('        rts')
w('')
w('; Meas - time the routine at Y with timer 2: B = timer 2 low byte after it (counting down from $FF)')
w('Meas:')
w('        ldx     #Buf')
w('        lda     #$FF')
w('        sta     $D008               ; timer 2 low latch')
w('        sta     $D009               ; high: load, start')
w('        jsr     ,y')
w('        ldb     $D008')
w('        rts')
w('')
w('T_base:')
w('        rts')
w('')
w('Sub:')
w('        rts')
for i, (lab, body) in enumerate(INST):
    w('')
    w('T_i%d:                               ; %s' % (i, lab))
    for l in body:
        w(l if l.startswith('@') else '        ' + l)
    w('        rts')
for i, (lab, body) in enumerate(VIA):
    w('')
    w('T_v%d:                               ; %s' % (i, lab))
    for l in body:
        w('        ' + l)
    w('        rts')
w('')
w('Nib:')
w('        adda    #$30')
w('        cmpa    #$39')
w('        bls     @n')
w('        adda    #7')
w('@n      rts')
w('')
w('Title   fcc     "CPU TIMING"')
w('        fcb     $80')
for r in range(4):
    t = 'ABCD'[r] + ' XX' * 8
    assert len(t) == ROWLEN - 1
    w('        fcc     "%s"' % t if r else 'RowTpl  fcc     "%s"' % t)
    w('        fcb     $80')

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cputime_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote cputime_test.asm')
