"""make_dac_test.py - writes dac_test.asm: how far the beam goes per cycle at each DAC value - is the deflection linear in
the DAC, and how long are the fixed delays at a line's start and end? (Made for Clean Sweep's centre box, 2026-10-26; the
owner's photos: linear, and lines meet the moves - see TODO.md.) Buttons 1-2
(controller 1) pick the page.

  page 1  ROWS: per DAC value D (32 .. 127) two horizontal lines from the same start (placed by Moveto_d at scale $7F):
          a long one of T = P / D cycles and a short one of T / 2 (Draw_Line_d at that scale). P is the same for all,
          so with a linear DAC every long line ends at one x - the vertical reference line there is placed by a move
          (scale $7F, X = P / 127): lines and moves meet where they agree. Long minus short: the speed per DAC value
          (the fixed delays cancel); twice short minus long: the delays.
  page 2  COLUMNS: the same, vertical (Y goes through its sample-and-hold).
The value of D printed at each row's left.
"""
import os

DACS = [32, 48, 64, 85, 96, 112, 127]
REF = 60                                         # (the long lines' nominal end: X (Y) = 60 at scale $7F from the start)
P = REF * 127                                    # (D x cycles of every long line)

def b8(v):
    return v & 0xFF

A = []
w = A.append
def ws(lines):
    for s in lines: w(s)

w('; dac_test.asm - generated by make_dac_test.py: the deflection speed per DAC value, two pages.')
w('; Build: lwasm --format=raw -o dac_test_raw.bin dac_test.asm, then pad to 32768 bytes with $FF.')
w('')
for name, adr in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Moveto_d', 0xF312),
                  ('Reset0Ref', 0xF354), ('Print_Str_d', 0xF37A), ('Draw_Line_d', 0xF3DF)):
    w('%-15s equ $%04X' % (name, adr))
w('Vec_Text_HW     equ $C82A')
w('Vec_Buttons     equ $C811')
w('Page            equ $C880')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "DAC TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('        clr     Page')
w('Main:')
w('        jsr     Wait_Recal')
w('        jsr     Read_Btns')
w('        lda     Vec_Buttons')
for k in range(2):
    w('        bita    #%d' % (1 << k))
    w('        beq     Bt%d' % k)
    w('        ldb     #%d' % k)
    w('        stb     Page')
    w('Bt%d' % k)
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
w('        lda     Page')
w('        lbeq    Page1')
w('        lbra    Page2')
w('')

def label(lbl, y, x):
    ws(['        lda     #$5F', '        jsr     Intensity_a', '        ldd     #$F830', '        std     Vec_Text_HW',
        '        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04',
        '        ldu     #%s' % lbl, '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Print_Str_d'])

def line(y, x, dy, dx, t):
    """from zero to (y, x) at scale $7F, then one line (dy, dx) at scale t"""
    ws(['        lda     #$7F', '        jsr     Intensity_a',
        '        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04',
        '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Moveto_d',
        '        lda     #%d' % t, '        sta     <$04',
        '        ldd     #$%02X%02X' % (b8(dy), b8(dx)), '        jsr     Draw_Line_d'])

X0, Y0 = -0x60, -0x60                            # (the lines' start: page 1 x, page 2 y)
rows = []
for d in DACS:
    t = int(round(P / float(d)))
    rows += [(d, t), (d, t // 2)]
w('Page1:')
for i, (d, t) in enumerate(rows):
    y = 0x74 - i * 0x0F
    if i % 2 == 0:
        label('L%d' % d, y + 3, -0x7E)
    line(y, X0, 0, d, t)
line(0x78, X0 + REF, -0x7F, 0, 0xFF)            # (the reference: where every long line ends if the DAC is linear,
line(0x78, X0, -0x7F, 0, 0xFF)                  #  and the start)
w('        lbra    Main')
w('')
w('Page2:')
for i, (d, t) in enumerate(rows):
    x = -0x74 + i * 0x0F
    if i % 2 == 0:
        label('L%d' % d, -0x76, x - 3)
    line(Y0, x, d, 0, t)
line(Y0 + REF, -0x7A, 0, 0x7F, 0xFF)
line(Y0, -0x7A, 0, 0x7F, 0xFF)
w('        lbra    Main')
w('')
for d in DACS:
    w('L%d      fcc     "%d"' % (d, d))
    w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'dac_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote dac_test.asm;', ', '.join('D%d: %d / %d cycles' % (d, t, t2) for (d, t), (_, t2) in zip(rows[::2], rows[1::2])))
