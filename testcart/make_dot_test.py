"""make_dot_test.py - writes dot_test.asm: four pages of dots for a photo of a real Vectrex (buttons 1-4 choose the page).

How bright and how big a dot is on a real tube - alone, at a line's joint, at a corner - decides the emulator's dots.
Everything timed by hand is drawn cycle-exact with the VIA (as corner_test): RAMP and the X speed change in one
16-bit store, the beam switched by CB2 (PCR $EE on, $CE off). The README's table has every parameter.
  1 ISOLATED  the beam on for N cycles without moving: N across, the intensity down; two plain lines to compare with
  2 GAME      the BIOS's dots (Dot_d with Vec_Dot_Dwell 1..80, Dot_List) and shots (36, 53, 66, 53 + 66, 119 cycles)
  3 INLINE    a line in 9 pieces with a rest at each joint (0, 5, 8, 11, 16, 24, 32, 48), at three speeds; a BIOS chain
  4 CORNERS   30, 45, 90, 135 degree corners with a rest of 0, 8, 16, 32, 64 at the corner; a BIOS square and triangle
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2, n
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

def b8(v):
    return v & 0xFF

X0, DX = -0x6C, 0x17                                # the label grid: 3 characters a column (corner_test's)
TEXT_W = 0x36
A = []
w = A.append

def text(label, y, x):
    w('        ldd     #$F8%02X' % TEXT_W)
    w('        std     Vec_Text_HW')
    w('        jsr     Reset0Ref')
    w('        lda     #$5F')
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04')
    w('        ldu     #%s' % label)
    w('        ldd     #$%02X%02X' % (b8(y), b8(x)))
    w('        jsr     Print_Str_d')

def row_start(z, y, x):
    w('        jsr     Reset0Ref')
    w('        lda     #$%02X' % z)
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04                ; scale $7F for the move')
    w('        ldd     #$%02X%02X' % (b8(y), b8(x)))
    w('        jsr     Moveto_d')

def hand_on():
    w('        lda     #$81')
    w('        sta     <$00                ; ramp off, mux off')
    w('        clr     <$0B                ; ACR: RAMP and /BLANK by hand')

def hand_off():
    w('        lda     #$98')
    w('        sta     <$0B                ; ACR back for the BIOS')

def rel_move(dy, dx):
    w('        lda     #$40')
    w('        sta     <$04                ; scale $40: units x 2')
    w('        ldd     #$%02X%02X' % (b8(dy), b8(dx)))
    w('        jsr     Moveto_d')

def dot(n):
    """the beam on for exactly n cycles, at rest (n = 4 or n >= 6)"""
    w('        lda     #$EE')
    w('        ldb     #$CE')
    w('        sta     <$0C                ; beam on')
    for s in delay(n - 4):
        w(s)
    w('        stb     <$0C                ; beam off: %d cycles' % n)

def set_y(vy):
    w('        lda     #$%02X' % b8(vy))
    w('        sta     <$01')
    w('        lda     #$80')
    w('        sta     <$00                ; mux on: the Y speed into its hold')
    for s in delay(8):
        w(s)
    w('        lda     #$81')
    w('        sta     <$00                ; mux off')

# ---------------------------------------------------------------- the pages' data (the README's table is made from these)
P1_N = [4, 8, 11, 16, 24, 32, 48, 64, 96, 128]
P1_ROWS = [(0x7F, 0x50), (0x5F, 0x38), (0x40, 0x20), (0x30, 0x08)]
P1_LINES = [(0x7F, -0x20), (0x5F, -0x38)]           # plain lines: Draw_Line_d, dx $50 at scale $FF
P2_DWELL = [1, 2, 5, 10, 20, 40, 80]
P2_DROWS = [(0x7F, 0x50), (0x5F, 0x34)]
P2_LIST_Y = 0x14
P2_SHOTS = ['36', '53', '66', '53+66', '119']
P2_SROWS = [(0x7F, -0x18), (0x5F, -0x38)]
P3_REST = [0, 5, 8, 11, 16, 24, 32, 48]
P3_ROWS = [(0x28, 70, 0x7F, 0x50), (0x50, 35, 0x7F, 0x30), (0x7F, 22, 0x7F, 0x10), (0x50, 35, 0x5F, -0x10)]   # speed, cycles a piece, intensity, y
P3_X0 = -0x64
P3_BIOS_Y = -0x38
P4_REST = [0, 8, 16, 32, 64]
P4_ROWS = [(30, 0x22, 0x7F, 0x5C), (45, 0x35, 0x7F, 0x34), (90, 0x7F, 0x7F, 0x0C), (135, 0x7F, 0x35, -0x1C)]   # angle, |vx|, |vy|, y
P4_L = 16
P4_SHAPE_Y = -0x40

if __name__ == '__main__':
    w('; dot_test.asm - generated by make_dot_test.py: dots alone, in games, on lines and at corners; buttons 1-4 = pages.')
    w('; Build: lwasm --format=raw -o dot_test_raw.bin dot_test.asm, then pad to 32768 bytes with $FF (64 KB: twice).')
    w('')
    for n, a in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Dot_d', 0xF2C3), ('Dot_List', 0xF2D5),
                 ('Moveto_d', 0xF312), ('Reset0Ref', 0xF354), ('Print_Str_d', 0xF37A), ('Draw_VLc', 0xF3CE), ('Draw_Line_d', 0xF3DF),
                 ('Vec_Btn_State', 0xC80F), ('Vec_Misc_Count', 0xC823), ('Vec_Dot_Dwell', 0xC828), ('Vec_Text_HW', 0xC82A), ('Page', 0xC880)):
        w('%-15s equ $%04X' % (n, a))
    w('')
    w('        org     $0000')
    w('        fcc     "g GCE 2026"')
    w('        fcb     $80')
    w('        fdb     $FD0D')
    w('        fcb     $F8,$50,$20,-$30')
    w('        fcc     "DOT TEST"')
    w('        fcb     $80')
    w('        fcb     0')
    w('')
    w('Start:  clr     Page')
    w('Main:   jsr     Wait_Recal')
    w('        lda     #$D0')
    w('        tfr     a,dp')
    w('        setdp   $D0')
    w('        jsr     Read_Btns')
    w('        lda     Vec_Btn_State')
    for i in range(4):
        w('        bita    #$%02X' % (1 << i))
        w('        beq     NoB%d' % i)
        w('        ldb     #%d' % i)
        w('        stb     Page')
        w('NoB%d:' % i)
    w('        ldb     Page')
    w('        lbeq    Page1')
    w('        decb')
    w('        lbeq    Page2')
    w('        decb')
    w('        lbeq    Page3')
    w('        lbra    Page4')

    # ------------------------------------------------------------ page 1: isolated dots
    w('')
    w('Page1:')
    for z, y in P1_ROWS:
        w('; dots at rest, intensity $%02X' % z)
        row_start(z, y, X0)
        for i, n in enumerate(P1_N):
            hand_on(); dot(n); hand_off()
            if i < len(P1_N) - 1:
                rel_move(0, DX * 2)
    for z, y in P1_LINES:
        w('; a plain line, intensity $%02X' % z)
        row_start(z, y, -0x50)
        w('        lda     #$FF')
        w('        sta     <$04                ; scale $FF')
        w('        ldd     #$0050')
        w('        jsr     Draw_Line_d         ; speed $50, 255 cycles')
    text('L1N', 0x68, X0 - 4)
    text('L1R', -0x50, -0x60)
    text('T1', -0x68, -0x50)
    w('        lbra    Main')

    # ------------------------------------------------------------ page 2: as games draw them
    w('')
    w('Page2:')
    for z, y in P2_DROWS:
        w('; the BIOS: Dot_d, Vec_Dot_Dwell across, intensity $%02X' % z)
        row_start(z, y, X0)
        for i, dw in enumerate(P2_DWELL):
            w('        lda     #%d' % dw)
            w('        sta     Vec_Dot_Dwell')
            w('        ldd     #$00%02X' % (DX if i else 0))
            w('        jsr     Dot_d               ; from the dot before (scale $7F)')
    w('        lda     #5')
    w('        sta     Vec_Dot_Dwell       ; the BIOS default again')
    w('; the BIOS: Dot_List, 6 dots, the default dwell')
    row_start(0x7F, P2_LIST_Y, X0)
    w('        lda     #5')
    w('        sta     Vec_Misc_Count')
    w('        ldx     #DotL')
    w('        jsr     Dot_List')
    for z, y in P2_SROWS:
        w('; shots: the beam on at rest, intensity $%02X' % z)
        row_start(z, y, X0)
        for i, s in enumerate(P2_SHOTS):
            hand_on()
            if '+' in s:
                a, b = [int(v) for v in s.split('+')]
                dot(a)
                for d in delay(12):
                    w(d)
                dot(b)
            else:
                dot(int(s))
            hand_off()
            if i < len(P2_SHOTS) - 1:
                rel_move(0, DX * 4)
    text('L2D', 0x68, X0 - 4)
#    text('L2L', 0x24, -0x60)
    text('L2S', -0x06, X0 - 4)
    text('T2', -0x68, -0x50)
    w('        lbra    Main')

    # ------------------------------------------------------------ page 3: dots inline
    w('')
    w('Page3:')
    for V, L, z, y in P3_ROWS:
        w('; a line in pieces: speed $%02X, %d cycles a piece, intensity $%02X' % (V, L, z))
        row_start(z, y, P3_X0)
        hand_on()
        set_y(0)
        w('        ldx     #$01%02X' % V)
        w('        ldy     #$81%02X' % V)
        w('        stx     <$00                ; ramp on, the X speed')
        w('        lda     #$EE')
        w('        sta     <$0C                ; beam on')
        for s in delay(L - 11):                                 # (STX .. STY: 2 + 4 + delay + 5)
            w(s)
        for n in P3_REST:
            if n == 0:
                for s in delay(L):
                    w(s)
            else:
                w('        sty     <$00                ; ramp off: rest %d' % n)
                for s in delay(n - 5):
                    w(s)
                w('        stx     <$00                ; ramp on')
                for s in delay(L - 5):
                    w(s)
        w('        sty     <$00                ; ramp off')
        w('        lda     #$CE')
        w('        sta     <$0C                ; beam off')
        hand_off()
    w('; the BIOS: 9 pieces with Draw_Line_d, as a game joins lines')
    row_start(0x7F, P3_BIOS_Y, P3_X0)
    for i in range(9):
        w('        ldd     #$0016')
        w('        jsr     Draw_Line_d')
    text('L3R', 0x68, -0x64)
    text('L3B', -0x28, -0x64)
    text('T3', -0x68, -0x50)
    w('        lbra    Main')

    # ------------------------------------------------------------ page 4: corners
    w('')
    w('Page4:')
    for ang, vx, vy, y in P4_ROWS:
        w('; corners of %d degrees: X speed -$%02X -> +$%02X, Y speed -$%02X' % (ang, vx, vx, vy))
        row_start(0x7F, y, X0 + 12)
        for i, n in enumerate(P4_REST):
            hand_on()
            set_y(-vy)
            w('        ldx     #$01%02X' % b8(-vx))
            w('        ldy     #$01%02X' % b8(vx))
            w('        stx     <$00                ; ramp on: piece 1')
            w('        lda     #$EE')
            w('        sta     <$0C                ; beam on')
            w('        ldd     #$81%02X' % b8(vx))
            for s in delay(P4_L - 13):
                w(s)
            if n == 0:
                w('        stb     <$01                ; the X speed flips, no stop')
                for s in delay(P4_L - 4):
                    w(s)
            else:
                w('        std     <$00                ; ramp off (+ the X speed of piece 2): rest %d' % n)
                for s in delay(n - 5):
                    w(s)
                w('        sty     <$00                ; ramp on: piece 2')
                for s in delay(P4_L - 5):
                    w(s)
            w('        std     <$00                ; ramp off')
            w('        lda     #$CE')
            w('        sta     <$0C                ; beam off')
            hand_off()
            if i < len(P4_REST) - 1:
                rel_move(round(vy * 2 * P4_L / 64.0), DX * 4)
    w('; the BIOS: a square and a triangle with Draw_VLc')
    row_start(0x7F, P4_SHAPE_Y, -0x40)
    w('        ldx     #Square')
    w('        jsr     Draw_VLc')
    row_start(0x7F, P4_SHAPE_Y, 0x18)
    w('        ldx     #Tri')
    w('        jsr     Draw_VLc')
    text('L4R', 0x70, X0 + 8)
    text('T4', -0x76, 0x10)
    w('        lbra    Main')

    # ------------------------------------------------------------ the data
    w('')
    w('DotL    fcb     0,0,0,%d,0,%d,0,%d,0,%d,0,%d' % ((DX,) * 5))
    w('Square  fcb     3,0,$28,-$28,0,0,-$28,$28,0')
    w('Tri     fcb     2,-$28,$18,0,-$30,$28,$18')
    def s(label, t):
        w('%-7s fcc     "%s"' % (label, t))
        w('        fcb     $80')
    s('L1N', ''.join('%-3d' % n for n in P1_N).rstrip())
    s('L1R', '7F 5F 40 30')
    s('T1', '1 ISOLATED')
    s('L2D', ''.join('%-3d' % n for n in P2_DWELL).rstrip())
    s('L2L', 'DOT LIST')
    s('L2S', ''.join('%-6s' % v for v in P2_SHOTS).rstrip())
    s('T2', '2 GAME')
    s('L3R', 'RESTS ' + ' '.join(str(n) for n in P3_REST))
    s('L3B', 'BIOS LINES')
    s('T3', '3 INLINE')
    s('L4R', ''.join('%-6d' % n for n in P4_REST).rstrip())
    s('T4', '4 CORNERS')

    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, 'dot_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
    # the cartridge images: 32 KB, and twice for a 64 KB EPROM
    raw = os.path.join(here, 'dot_test_raw.bin')
    if os.path.exists(raw) and '--pack' in os.sys.argv:
        d = open(raw, 'rb').read(); assert len(d) <= 32768, len(d)
        d += b'\xff' * (32768 - len(d))
        open(os.path.join(here, 'dot_test.bin'), 'wb').write(d); open(os.path.join(here, 'dot_test_64k.bin'), 'wb').write(d + d)
        os.remove(raw); print('packed dot_test.bin (32 KB), dot_test_64k.bin')
    else:
        print('wrote dot_test.asm')
