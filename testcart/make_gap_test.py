"""make_gap_test.py - writes gap_test.asm: the gaps between joined lines, drawn with the BIOS's Draw_VLp (as Mine Storm
draws its ship and mines), easy to measure on a photo. Buttons 1-3 (controller 1) pick the page.

  page 1  ROWS: per scale S = 6..13 (one full period of Draw_VLp's 7-cycle wait loop) a horizontal row of 10 joined
          segments, speed $7F, each S cycles long; the scale printed at its left. Each gap's share of its segment is
          (the gap in cycles) / S - whatever the speed - and the rest dots sit at the joins.
  page 2  COLUMNS: the same, vertical (Y goes through its sample-and-hold: its timing may differ).
  page 3  SQUARES: a closed square per scale 6..13, two rows of four, each side two segments: the gaps at corners
          (Mine Storm's ship and mines are such corners) and on a straight join.
The labels are two characters ("S6".."13": the BIOS text routine misbehaves with one).
"""
import os

SCALES = [6, 7, 8, 9, 10, 11, 12, 13]
V = 0x7F                                         # (the speed: DAC steps a cycle)
NSEG = 10                                        # (segments a row / column)

def b8(v):
    return v & 0xFF

A = []
w = A.append
def ws(lines):
    for s in lines: w(s)

w('; gap_test.asm - generated by make_gap_test.py: the gaps between joined lines (Draw_VLp), three pages.')
w('; Build: lwasm --format=raw -o gap_test_raw.bin gap_test.asm, then pad to 32768 bytes with $FF.')
w('')
for name, adr in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Moveto_d', 0xF312),
                  ('Reset0Ref', 0xF354), ('Print_Str_d', 0xF37A), ('Draw_VLp', 0xF410)):
    w('%-15s equ $%04X' % (name, adr))
w('Vec_Text_HW     equ $C82A')
w('Vec_Buttons     equ $C811')
w('Page            equ $C880')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "GAP TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('        clr     Page')
w('Main:')
w('        jsr     Wait_Recal')
w('        jsr     Read_Btns')
w('        lda     Vec_Buttons')
for k in range(3):
    w('        bita    #%d' % (1 << k))
    w('        beq     Bt%d' % k)
    w('        ldb     #%d' % k)
    w('        stb     Page')
    w('Bt%d' % k)
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
w('        lda     Page')
w('        lbeq    Page1')
w('        deca')
w('        lbeq    Page2')
w('        lbra    Page3')
w('')

def label(lbl, y, x):
    ws(['        lda     #$5F', '        jsr     Intensity_a', '        ldd     #$F830', '        std     Vec_Text_HW',
        '        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04',
        '        ldu     #%s' % lbl, '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Print_Str_d'])

def draw(lst, y, x, s):
    """from zero to (y, x) at scale $7F, then the list with Draw_VLp at scale s"""
    ws(['        lda     #$7F', '        jsr     Intensity_a',
        '        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04',
        '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Moveto_d',
        '        lda     #%d' % s, '        sta     <$04',
        '        ldx     #%s' % lst, '        jsr     Draw_VLp'])

# page 1: rows (y from +$50 down, x from -$58)
w('Page1:')
for i, s in enumerate(SCALES):
    y = 0x50 - i * 0x16
    label('Ls%d' % s, y + 4, -0x7C)
    draw('Hrow', y, -0x68, s)
w('        lbra    Main')
w('')
# page 2: columns (x from -$5A right, y from -$50 up)
w('Page2:')
for i, s in enumerate(SCALES):
    x = -0x5A + i * 0x18
    label('Ls%d' % s, -0x74, x - 4)
    draw('Vcol', -0x68, x, s)
w('        lbra    Main')
w('')
# page 3: squares, two rows of four
w('Page3:')
for i, s in enumerate(SCALES):
    x = -0x6C + (i % 4) * 0x38; y = 0x18 - (i // 4) * 0x60
    label('Ls%d' % s, y + 0x44, x)
    draw('Sq%d' % s, y, x, s)
w('        lbra    Main')
w('')
# the lists (Draw_VLp: pattern, y, x; $FF draw, $01 end). Rows / columns: 6 segments at V a cycle, the scale sets the
# length; squares: sides of ~1300 units at every scale (the speed V * 13 / s)
w('Hrow:')
for _ in range(NSEG): w('        fcb     $FF,0,$%02X' % V)
w('        fcb     $01')
w('Vcol:')
for _ in range(NSEG): w('        fcb     $FF,$%02X,0' % V)
w('        fcb     $01')
for s in SCALES:
    v = min(127, int(round(0x64 * 13 / s)))      # (sides of ~2600 units where the speed allows)
    w('Sq%d:' % s)
    for dy, dx in ((v, 0), (v, 0), (0, v), (0, v), (-v, 0), (-v, 0), (0, -v), (0, -v)):
        w('        fcb     $FF,$%02X,$%02X' % (b8(dy), b8(dx)))
    w('        fcb     $01')
for s in SCALES:
    w('Ls%d     fcc     "%s"' % (s, ('S%d' % s) if s < 10 else str(s)))
    w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'gap_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote gap_test.asm')
