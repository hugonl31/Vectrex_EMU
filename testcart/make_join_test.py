COL_X = [-0x70, -0x38, 0x00, 0x38]
BIOS_N = [6, 8, 11, 13]
ROW_Y0, ROW_DY = 0x58, 0x14
WANT_OFF = [2, 5, 8, 11, 14, 17, 20, 24, 32]
WANT_ON = [-12, -8, -4, 4, 8, 12, 16, 20]
STB5 = ('stb     <$05', 4, 4)                               # timer 1's high counter: the one-shot starts
YK = [[5, 7, 8, 10], [12, 16, 20, 24]]
Y_V, Y_L, Y_REST = 0x50, 20, 60

def bios_line(N, k_off=None, k_on=None):
    """the shift register on, timer 1 started (t0 = 24), the shift register off - all by the cycle; ACR as the BIOS's ($98)"""
    w('        lda     #$81'); w('        sta     <$00                ; mux off')
    set_y(0)
    w('        lda     #$7F'); w('        sta     <$01                ; the X speed'); w('        lda     #$%02X' % N); w('        sta     <$04                ; timer 1: %d cycles' % N)
    w('        lda     #$FF'); w('        clrb')
    t0 = 24
    run([(t0, STB5), (t0 - 4 if k_on is None else t0 + k_on, STASR), (t0 + N + (40 if k_off is None else k_off), STBSR)])
    w('        clr     <$01                ; the X speed 0')

def y_fig(k, M):
    """leg 1 (X +v, Y -v), RAMP off; the Y hold loaded (+v) through the mux open M cycles; RAMP on k cycles after it closes"""
    v = Y_V
    hand_on(); set_y(-v)
    w('        ldx     #$01%02X' % v)
    s = Sched(); s.write('stx     <$00', 5, 4, 10)                      # RAMP on, the X speed
    s.op('lda     #$EE', 2); s.write('sta     <$0C', 4, 4, 17)          # the beam on
    s.op('lda     #$81', 2); t_off = 10 + Y_L; s.write('sta     <$00', 4, 4, t_off)   # RAMP off
    t_on = t_off + Y_REST; t_mc = t_on - k; t_mo = t_mc - M             # the mux opens / closes
    s.op('lda     #$%02X' % v, 2); s.write('sta     <$01', 4, 4, t_mo - 6)            # the DAC: the new Y speed
    s.op('lda     #$80', 2); s.write('sta     <$00', 4, 4, t_mo)        # the mux open (RAMP off)
    s.op('ldd     #$81%02X' % v, 3); s.write('std     <$00', 5, 4, t_mc)             # the mux closed, then the DAC back to the X speed
    s.write('stx     <$00', 5, 4, t_on)                                 # RAMP on: leg 2
    s.op('lda     #$81', 2); s.write('sta     <$00', 4, 4, t_on + Y_L)  # RAMP off
    s.op('lda     #$CE', 2); s.op('sta     <$0C', 4)                    # the beam off
    hand_off()

def emit_bios(page, wants, off):
    TABLE[page] = []
    for ci, N in enumerate(BIOS_N):
        ks = []
        for i, k in enumerate(wants):
            w('; page %d, N %d, row %d' % (page, N, i + 1))
            row_start(0x7F, ROW_Y0 - i * ROW_DY, COL_X[ci])
            ks.append(try_line((lambda k, N=N: bios_line(N, k_off=k)) if off else (lambda k, N=N: bios_line(N, k_on=k)), k, ks))
        TABLE[page].append(ks)

def emit_y(M):
    for r, row in enumerate(YK):
        for i, k in enumerate(row):
            w('; Y hold: the mux open %d cycles, RAMP on %d cycles after it closes' % (M, k))
            row_start(0x7F, 0x50 - r * 0x50, -0x68 + i * 0x34); y_fig(k, M)

