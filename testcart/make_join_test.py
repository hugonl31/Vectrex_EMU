"""make_join_test.py - writes join_test.asm ("JOIN TEST"): the BIOS's own way of drawing a short line, by hand, with one
thing varied - and the Y speed's hold (the one path no cart has timed yet). Buttons 1-4; 50 Hz; every write on its cycle.

Page 1  BIOS OFF  as the BIOS draws: the shift register $FF written 4 cycles before timer 1 starts (t0), RAMP by timer 1
                  for N = 6, 8, 11, 13 cycles (columns) at speed $7F; the shift register $00 written K cycles after t0 + N
                  (rows) - the BIOS itself does it ~10 - 16 cycles after.
Page 2  BIOS ON   the same, the shift register $FF written K cycles after t0 (the BIOS: -4), $00 written 40 after t0 + N.
Page 3  Y HOLD    a "V": leg 1 down-right, a rest of 60 cycles, leg 2 up-right. The new Y speed goes into its hold through
                  the multiplexer (open 12 cycles) and RAMP comes on K cycles after the multiplexer closes: K = 5, 7, 8, 10
                  (top row), 12, 16, 20, 24 (bottom row). If the hold is late the second leg starts downwards.
Page 4  Y HOLD 7  the same with the multiplexer open only 7 cycles (how fast the hold charges).
"""
