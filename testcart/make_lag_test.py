"""make_lag_test.py - writes lag_test.asm: one page measuring how the spot follows the integrators.

The beam is switched (/BLANK, PCR) at exact cycles relative to RAMP (the integrators on / off), so the lit part of a
line shows where the spot was at those moments. Every sample: a horizontal line at speed $28, intensity $7F,
after 40 cycles at rest (the spot settled). Drawn cycle-exact through the VIA; RAMP / /BLANK writes are scheduled
to the cycle (the cycle of a store's write: the end of the instruction).

  row A  START: RAMP on at 0, the beam on at k (k = -4, 4, 6, 8, 10, 12, 16, 20, 24, 32, 40), RAMP off at 48, the
         beam off at 54. The lit line's start moves along with k: how the spot gets moving (the start delay, the lag)
  row B  END: the beam on at -4, RAMP on at 0, off at 48, the beam off at 48 + k (k = 4, 6, 8, 10, 12, 16, 20, 24,
         32, 40, 64). The lit line's end grows with k until the spot has stopped (the stop delay, the lag)
  row C  SCALE: the beam on at -4, RAMP on at 0, off at T (T = 8, 16, 24, 32, 40, 48, 56, 64), the beam off at T + 64:
         the whole path, both ends at rest (dots). Its length per cycle: the photo's scale; at T = 0: the stop
         delay minus the start delay
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2, n
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

def schedule(events):
    """events: (cycle, address, value), the cycle of the write (a store's last cycle). Returns code: register loads
    (the next value preloaded into the other register where there is time) and delays so each STA / STB (4 cycles,
    direct page) writes at its cycle; the first event is at its own end"""
    events = sorted(events)
    code, regs = [], {'a': None, 'b': None}
    def load(r, v):
        regs[r] = v; return '        ld%s     #$%02X' % (r, v)
    # before the first store: its value and the next one in the two registers
    code.append(load('a', events[0][2]))
    if len(events) > 1 and events[1][2] != events[0][2]:
        code.append(load('b', events[1][2]))
    t = None
    for i, (when, addr, val) in enumerate(events):
        nxt = events[i + 1][2] if i + 1 < len(events) else None
        pre = []
        r = 'a' if regs['a'] == val else 'b' if regs['b'] == val else None
        if r is None:
            r = 'b' if regs['a'] == nxt else 'a'
            pre.append(load(r, val))
        other = 'b' if r == 'a' else 'a'
        keep = regs[other]
        if nxt is not None and nxt != val and regs[other] != nxt:
            pre.append(load(other, nxt))                    # (the next value, ahead of time)
            ahead = True
        else:
            ahead = False
        if t is None:
            t = when - 4 - 2 * len(pre); code += pre
        else:
            gap = when - 4 - t - 2 * len(pre)
            if ahead and (gap < 0 or gap == 1):             # (no time to preload: not now)
                regs[other] = keep; pre = pre[:-1]; gap += 2
            assert gap == 0 or gap >= 2, ('cannot schedule', events[i - 1], events[i], gap)
            code += pre + delay(gap)
            t += 2 * len(pre) + gap
        code.append('        st%s     <$%02X               ; @%d: $%02X' % (r, addr, when, val))
        t += 4
    return code

V = 0x28                                    # the line speed (DAC)
T_A = 48
KA = [-4, 4, 6, 8, 10, 12, 16, 20, 24, 32, 40]
KB = [4, 6, 8, 10, 12, 16, 20, 24, 32, 40, 64]
TC = [8, 16, 24, 32, 40, 48, 56, 64]
ORB, ORA, PCR = 0x00, 0x01, 0x0C
RAMP_ON, RAMP_OFF, BEAM_ON, BEAM_OFF = 0x01, 0x81, 0xEE, 0xCE
ROWS = [('A', 0x48, -0x70, 0x14, KA), ('B', 0x10, -0x70, 0x14, KB), ('C', -0x28, -0x70, 0x1C, TC)]
LAB_DY = 0x0E

def sample(kind, k):
    if kind == 'A':
        ev = [(0, ORB, RAMP_ON), (k, PCR, BEAM_ON), (T_A, ORB, RAMP_OFF), (T_A + 6, PCR, BEAM_OFF)]
        T = T_A
    elif kind == 'B':
        ev = [(-4, PCR, BEAM_ON), (0, ORB, RAMP_ON), (T_A, ORB, RAMP_OFF), (T_A + k, PCR, BEAM_OFF)]
        T = T_A
    else:
        ev = [(-4, PCR, BEAM_ON), (0, ORB, RAMP_ON), (k, ORB, RAMP_OFF), (k + 64, PCR, BEAM_OFF)]
        T = k
    return schedule(ev), T

A = []
w = A.append
w('; lag_test.asm - generated by make_lag_test.py: how the spot follows the integrators, one page.')
w('; Build: lwasm --format=raw -o lag_test_raw.bin lag_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Moveto_d        equ $F312')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Vec_Text_HW     equ $C82A')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "LAG TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('Main:')
w('        jsr     Wait_Recal')
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
for kind, y, x0, dx, ks in ROWS:
    w('')
    w('; row %s' % kind)
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04                ; scale $7F for the moves')
    w('        ldd     #$%02X%02X' % (y & 0xFF, x0 & 0xFF))
    w('        jsr     Moveto_d')
    w('        lda     #$40')
    w('        sta     <$04                ; scale $40 for the moves between the samples')
    for i, k in enumerate(ks):
        code, T = sample(kind, k)
        w('; %s k = %d' % (kind, k))
        w('        lda     #$81')
        w('        sta     <$00                ; ramp off, mux off')
        w('        clr     <$0B                ; ACR: PB7 = RAMP and CB2 = /BLANK by hand')
        w('        clr     <$01')
        w('        lda     #$80')
        w('        sta     <$00                ; mux on: Y speed 0 into its hold')
        for s in delay(8):
            w(s)
        w('        lda     #$81')
        w('        sta     <$00                ; mux off')
        w('        lda     #$%02X' % V)
        w('        sta     <$01                ; X speed')
        for s in delay(40):                      # (the spot at rest: settled)
            w(s)
        for s in code:
            w(s)
        w('        lda     #$98')
        w('        sta     <$0B                ; ACR back for the BIOS')
        if i < len(ks) - 1:
            moved = V * T / 64.0                 # (units at scale $40)
            ddx = round(dx * 2 - moved)
            w('        ldd     #$00%02X' % (ddx & 0xFF))
            w('        jsr     Moveto_d            ; to the next sample')
# the labels: k (or T) above each column, 3 characters a column
w('')
w('        lda     #$5F')
w('        jsr     Intensity_a')
for kind, y, x0, dx, ks in ROWS[:2]:          # (row C unlabelled: T = 8 .. 64, left to right - time)
    tw = int(round(0x36 * (dx / 3.0) / 7.5))
    w('        ldd     #$F8%02X' % tw)
    w('        std     Vec_Text_HW')
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        sta     <$04')
    w('        ldu     #Lab%s' % kind)
    w('        ldd     #$%02X%02X' % ((y + LAB_DY) & 0xFF, (x0 - 3) & 0xFF))
    w('        jsr     Print_Str_d')
w('        lbra    Main')
w('')
for kind, y, x0, dx, ks in ROWS[:2]:
    w('Lab%s    fcc     "%s"' % (kind, ''.join('%-3d' % k for k in ks).rstrip()))
    w('        fcb     $80')

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, 'lag_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote lag_test.asm')
