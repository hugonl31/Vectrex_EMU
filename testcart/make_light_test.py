"""make_light_test.py - writes light_test.asm ("LIGHT TEST"): the phosphor's light against how the beam moves.
Buttons 1-4; 50 Hz.

Page 1  SPEED 7F / 40   a line of ~30 units at nine constant speeds (rows, top to bottom: $7F, $60, $40, $30, $20, $18,
                        $10, $08, $04 - the beam lingers 1 to 32 cycles a unit), RAMP by hand; left column intensity $7F,
                        right $40. The light a unit of line against the dwell.
Page 2  SPEED 5F / 30   the same at intensities $5F and $30.
Page 3  REPEAT / CROSS  top: one line (BIOS Draw_Line_d, 40 units) drawn 1, 2, 4, 8 times in the frame (rows), left
                        intensity $7F, right $3F (1 and 2 times only) - how the phosphor adds light when hit again. Bottom: three lines down
                        crossing three lines across (the crossings: two hits a few hundred cycles apart).
Page 4  SPOT            rows: intensity $1F, $3F, $5F, $6F, $7F; in each of three columns (left, middle, right of
                        the screen) a line of 16 units and a dot (the beam on 20 cycles at rest): the line's width and the
                        dot's size by intensity and place.
"""
import make_dot_test as D
from tc_common import *

SPEEDS = [0x7F, 0x60, 0x40, 0x30, 0x20, 0x18, 0x10, 0x08, 0x04]
LEN_U = 30.0                                                # the line's length, units
ROW_Y0, ROW_DY = 0x58, 0x14

def speed_line(v):
    """RAMP on, the beam on, n loop passes of 8 cycles, RAMP off, 40 cycles, the beam off"""
    cyc = LEN_U * 133.1 / v; n = max(1, int(round((cyc - 12) / 8.0)))
    hand_on(); set_y(0)
    w('        ldx     #$01%02X' % v); w('        lda     #$EE'); w('        ldb     #$CE')
    w('        stx     <$00                ; ramp on, the X speed $%02X' % v)
    w('        sta     <$0C                ; beam on')
    w('        ldx     #%d                 ; ~%d cycles' % (n, n * 8 + 12))
    w('        leax    -1,x'); w('        bne     *-2')
    w('        lda     #$81'); w('        sta     <$00                ; ramp off')
    for s in delay(40): w(s)
    w('        stb     <$0C                ; beam off')
    w('        clr     <$01'); hand_off()

def emit_speed(zs):
    for ci, z in enumerate(zs):
        for i, v in enumerate(SPEEDS):
            w('; speed $%02X at intensity $%02X' % (v, z)); row_start(z, ROW_Y0 - i * ROW_DY, -0x70 + ci * 0x70); speed_line(v)

def bios_line(z, y, x, dy, dx):
    w('        jsr     Reset0Ref'); w('        lda     #$%02X' % z); w('        jsr     Intensity_a'); w('        lda     #$7F'); w('        sta     <$04')
    w('        ldd     #$%02X%02X' % (b8(y), b8(x))); w('        jsr     Moveto_d')
    w('        ldd     #$%02X%02X' % (b8(dy), b8(dx))); w('        jsr     Draw_Line_d')

def build():
    begin('LIGHT TEST', 'light_test.asm - generated by make_light_test.py: light against dwell, repeats, crossings, the spot; buttons 1-4.')
    page(1); emit_speed((0x7F, 0x40)); text('L1', 0x70, -0x70); text('T1', -0x74, -0x50); page_end()
    page(2); emit_speed((0x5F, 0x30)); text('L2', 0x70, -0x70); text('T2', -0x74, -0x50); page_end()
    page(3)
    for ci, z in enumerate((0x7F, 0x3F)):
        for i, n in enumerate((1, 2, 4, 8)):
            if ci == 1 and n in (4, 8): continue            # (the frame's 30000 cycles: the right column 1 and 2 times only)
            for k in range(n):
                w('; the line %d of %d times, intensity $%02X' % (k + 1, n, z)); bios_line(z, 0x58 - i * 0x14, -0x70 + ci * 0x70, 0, 0x28)
    for i in range(3): bios_line(0x7F, -0x18, -0x20 + i * 0x18, -0x40, 0)        # three lines down
    for i in range(3): bios_line(0x7F, -0x28 - i * 0x10, -0x30, 0, 0x50)         # three lines across
    text('L3', 0x70, -0x70); text('T3', -0x74, -0x50); page_end()
    page(4)
    for i, z in enumerate((0x1F, 0x3F, 0x5F, 0x6F, 0x7F)):
        for x in (-0x70, -0x14, 0x48):
            bios_line(z, 0x58 - i * 0x18, x, 0, 0x10)
            row_start(z, 0x58 - i * 0x18, x + 0x1C); hand_on(); D.dot(20); hand_off()
    text('L4', 0x70, -0x70); text('T4', -0x74, -0x50); page_end()
    w('')
    string('L1', 'SPEED 7F TO 04   Z 7F / 40'); string('T1', '1 SPEED')
    string('L2', 'SPEED 7F TO 04   Z 5F / 30'); string('T2', '2 SPEED')
    string('L3', 'REPEAT 1 2 4 8   Z 7F / 3F 1 2'); string('T3', '3 REPEAT CROSS')
    string('L4', 'SPOT  Z 1F TO 7F'); string('T4', '4 SPOT')
    finish('light_test', 'Light Test')

if __name__ == '__main__':
    build()
