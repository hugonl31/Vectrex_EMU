"""make_photo_test.py - writes photo_test.asm ("PHOTO TEST"): the Light, BIOS Timing, Shapes and Rate tests on one
cartridge, sixteen pages. Joystick right / button 4: the next page; joystick left / button 1: the one before. Every
page's title starts with its number ("07/16 ..."). Pages 1-12 run at 50 Hz, 13-16 are the Rate Test (50, 40, 30, 25 Hz).

 1- 4  Light Test    (make_light_test.py):  speed 7F/40, speed 5F/30, repeat + cross, spot
 5- 8  BIOS Timing   (make_bios_test.py):   SR gap, SR byte, timer 1's flag, X and Y
 9-12  Shapes Test   (make_shapes_test.py): Draw_VLc, Draw_VLp, patterns, text
13-16  Rate Test     (make_rate_test.py):   50, 40, 30, 25 frames a second
"""
import re
import tc_common as T
from tc_common import w, A, EQU
import make_light_test, make_bios_test, make_shapes_test, make_rate_test

MODS = [('a', make_light_test), ('b', make_bios_test), ('c', make_shapes_test), ('d', make_rate_test)]
NP = 16
RATE = {12: 30000, 13: 37500, 14: 50000, 15: 60000}        # page index -> the frame's cycles (the others 30000)

def build():
    del A[:]
    w('; photo_test.asm - generated by make_photo_test.py: sixteen pages (Light, BIOS Timing, Shapes, Rate); joystick / buttons 1 and 4.'); w('')
    for n, a in EQU + (('Joy_Digital', 0xF1F8), ('Vec_Joy_1_X', 0xC81B), ('Vec_Joy_Mux', 0xC81F), ('Vec_Button_1_1', 0xC812), ('Vec_Button_1_4', 0xC815), ('JoyLast', 0xC882)):
        w('%-15s equ $%04X' % (n, a))
    w('')
    w('        org     $0000'); w('        fcc     "g GCE 2026"'); w('        fcb     $80'); w('        fdb     $FD0D')
    w('        fcb     $F8,$50,$20,-$40'); w('        fcc     "PHOTO TEST"'); w('        fcb     $80'); w('        fcb     0')
    w('')
    w('Start:  clr     Page'); w('        clr     JoyLast')
    w('Main:   lda     Page'); w('        asla'); w('        ldx     #RateTab'); w('        ldd     a,x'); w('        std     Vec_Rfrsh          ; the frame timer of this page')
    w('        jsr     Wait_Recal'); w('        lda     #$D0'); w('        tfr     a,dp'); w('        setdp   $D0')
    w('        jsr     Read_Btns')
    w('        ldd     #$0100'); w('        std     Vec_Joy_Mux         ; joystick 1: X only'); w('        clr     Vec_Joy_Mux+2'); w('        clr     Vec_Joy_Mux+3')
    w('        jsr     Joy_Digital')
    w('        lda     Vec_Joy_1_X'); w('        cmpa    JoyLast'); w('        beq     NoJoy'); w('        sta     JoyLast'); w('        tsta'); w('        beq     NoJoy'); w('        bmi     Prev'); w('        bra     Next')
    w('NoJoy:  lda     Vec_Button_1_4'); w('        bne     Next'); w('        lda     Vec_Button_1_1'); w('        bne     Prev'); w('        bra     Go')
    w('Next:   lda     Page'); w('        inca'); w('        cmpa    #%d' % NP); w('        blo     SetP'); w('        clra'); w('        bra     SetP')
    w('Prev:   lda     Page'); w('        deca'); w('        bpl     SetP'); w('        lda     #%d' % (NP - 1))
    w('SetP:   sta     Page')
    w('Go:     ldb     Page'); w('        aslb'); w('        ldx     #PageTab'); w('        jmp     [b,x]')
    gp = [0]
    for pre, mod in MODS:
        base = gp[0]; start = len(A); loc = [0]
        def page(n, base=base): loc[0] = n; w(''); w('Pg%02d:' % (base + n))
        def page_end(): w('        lbra    Main')
        def string(label, t, base=base):
            m = re.fullmatch(r'T([1-4])', label); r = re.fullmatch(r'R(50|40|30|25)', label)
            if m: t = '%02d/%d %s' % (base + int(m.group(1)), NP, t[2:])            # (the module's own "1 " replaced)
            if r: t = '%02d/%d %s' % (base + 1 + ['50', '40', '30', '25'].index(r.group(1)), NP, t)
            w('%-7s fcc     "%s"' % (label, t)); w('        fcb     $80')
        mod.begin = lambda *a, **k: None; mod.page = page; mod.page_end = page_end; mod.string = string; mod.finish = lambda *a, **k: None
        mod.build()
        for i in range(start, len(A)):
            if ' fcc ' in A[i]: A[i] = re.sub(r'^(L[1-4]|T[1-4]|Txt|R50|R40|R30|R25)\b', lambda m_: pre + m_.group(1), A[i])   # (a string: its label only)
            else: A[i] = re.sub(r'\b(L[1-4]|T[1-4]|Txt|R50|R40|R30|R25)\b', lambda m_: pre + m_.group(1), A[i])
            if A[i].startswith('RateTab:') or 'RateTab' in A[i] and 'equ' not in A[i]: A[i] = A[i].replace('RateTab', pre + 'RateTab')
        gp[0] += 4
    w('')
    w('PageTab:')
    for i in range(NP): w('        fdb     Pg%02d' % (i + 1))
    w('RateTab:')
    for i in range(NP):
        c = RATE.get(i, 30000); w('        fcb     $%02X,$%02X          ; page %d: %d cycles' % (c & 255, c >> 8, i + 1, c))
    T.finish('photo_test', 'Photo Test')

if __name__ == '__main__':
    import sys
    if '--pack' in sys.argv: T.finish('photo_test', 'Photo Test')
    else: build()
