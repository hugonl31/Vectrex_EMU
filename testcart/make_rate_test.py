"""make_rate_test.py - writes rate_test.asm ("RATE TEST"): one picture at four refresh rates. Buttons 1-4: 50, 40, 30,
25 frames a second (the BIOS's frame timer Vec_Rfrsh: 30000, 37500, 50000, 60000 cycles). The picture: five lines of
40 units at intensities $7F, $5F, $3F, $2F, $1F with a dot (the beam on 20 cycles at rest) after each, and the rate
as text. The light a frame is the same on every page; the eye's (and a long exposure's) light follows the rate and
the phosphor's decay between the frames.
"""
import make_dot_test as D
from tc_common import *

RATES = [(50, 30000), (40, 37500), (30, 50000), (25, 60000)]

def hook():
    """before Wait_Recal: the frame timer for the page"""
    w('        lda     Page'); w('        asla'); w('        ldx     #RateTab'); w('        ldd     a,x'); w('        std     Vec_Rfrsh')

def picture(label):
    for i, z in enumerate((0x7F, 0x5F, 0x3F, 0x2F, 0x1F)):
        w('        jsr     Reset0Ref'); w('        lda     #$%02X' % z); w('        jsr     Intensity_a'); w('        lda     #$7F'); w('        sta     <$04')
        w('        ldd     #$%02X%02X' % (b8(0x40 - i * 0x20), b8(-0x50))); w('        jsr     Moveto_d')
        w('        ldd     #$0028'); w('        jsr     Draw_Line_d')
        row_start(z, 0x40 - i * 0x20, 0x10); hand_on(); D.dot(20); hand_off()
    text(label, 0x70, -0x50)

def build():
    begin('RATE TEST', 'rate_test.asm - generated by make_rate_test.py: one picture at 50, 40, 30, 25 frames a second; buttons 1-4.', hook)
    for p, (hz, cyc) in enumerate(RATES):
        page(p + 1); picture('R%d' % hz); page_end()
    w('')
    w('RateTab:')
    for hz, cyc in RATES: w('        fcb     $%02X,$%02X          ; %d cycles (low byte first): %d Hz' % (cyc & 255, cyc >> 8, cyc, hz))
    for hz, cyc in RATES: string('R%d' % hz, '%d HZ' % hz)
    finish('rate_test', 'Rate Test')

if __name__ == '__main__':
    build()
