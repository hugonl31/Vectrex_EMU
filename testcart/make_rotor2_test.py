# make_rotor_test.py - writes rotor2_test.asm: three helicopter-like rotors (4 blades each) spinning at
# 2, 5 and 9 steps of 64 per frame, for checking the afterglow of fast-turning lines.
# Build: lwasm --format=raw -o rotor_test_raw.bin rotor2_test.asm, then pad to 32768 bytes with $FF.
import math, os

R = 50
tab = []
for i in range(64):
    a = 2 * math.pi * i / 64
    tab.append((round(R * math.sin(a)), round(R * math.cos(a))))

ROTORS = [((40, -70), 2), ((40, 70), 5), ((-55, 0), 9)]   # (centre y, x at scale $7F), steps per frame

s = []
w = s.append
w("""; rotor2_test.asm - generated by make_rotor_test.py: three 4-blade rotors spinning at 2, 5 and 9 / 64 turns per frame.
; Build: lwasm --format=raw -o rotor_test_raw.bin rotor2_test.asm, then pad to 32768 bytes with $FF.

Wait_Recal      equ $F192
Intensity_a     equ $F2AB
Moveto_d        equ $F312
Draw_Line_d     equ $F3DF
Reset0Ref       equ $F354

Angles          equ $C880           ; one byte per rotor
Blade           equ $C884           ; the blade's angle now
Count           equ $C885
Tmp             equ $C886

        org     $0000
        fcc     "g GCE 2026"
        fcb     $80
        fdb     $FD0D
        fcb     $F8,$50,$20,-$40
        fcc     "ROTOR TEST 2"
        fcb     $80
        fcb     0

Start:
        clr     Angles
        clr     Angles+1
        clr     Angles+2
Main:
        jsr     Wait_Recal
        lda     #$7F
        jsr     Intensity_a
""")
for k, ((cy, cx), sp) in enumerate(ROTORS):
    w("""; rotor %d
        jsr     Reset0Ref
        lda     #$7F
        sta     $D004
        lda     #%d
        ldb     #%d
        jsr     Moveto_d
        lda     #$30
        sta     $D004
        lda     Angles+%d
        adda    #%d
        anda    #63
        sta     Angles+%d
        sta     Blade
        lda     #4
        sta     Count
        jsr     Rotor
""" % (k, cy, cx, k, sp, k))
w("""        jmp     >Main               ; (extended: Main sits below $100 and DP is $D0)

; the four blades from the beam's place now (the hub): out along a blade, back to the hub with the beam off
Rotor:
        lda     Blade
        lsla
        ldx     #Tips
        leax    a,x
        ldd     ,x
        clr     $C823               ; Vec_Misc_Count: one line only
        jsr     Draw_Line_d
        lda     Blade
        lsla
        ldx     #Back
        leax    a,x
        ldd     ,x
        std     Tmp
        lda     Blade
        lsla
        ldx     #Perp
        leax    a,x
        ldd     ,x
        jsr     Moveto_d            ; across to the blade's second line
        ldd     Tmp
        clr     $C823
        jsr     Draw_Line_d         ; back to the hub, beside the first
        lda     Blade
        lsla
        ldx     #NPerp
        leax    a,x
        ldd     ,x
        jsr     Moveto_d            ; across back to the hub
        lda     Blade
        adda    #16
        anda    #63
        sta     Blade
        dec     Count
        bne     Rotor
        rts

Tips:
""")
for y, x in tab:
    w("        fcb     %d,%d\n" % (y, x))
for nm, sg in (("Perp", 1), ("NPerp", -1)):     # (across a blade, to its second line, and back)
    w(nm + ":\n")
    for i in range(64):
        a = 2 * math.pi * i / 64
        w("        fcb     %d,%d\n" % (sg * round(4 * math.cos(a)), sg * round(-4 * math.sin(a))))
w("Back:\n")
for y, x in tab:
    w("        fcb     %d,%d\n" % (-y, -x))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rotor2_test.asm'), 'w', newline='\n').write(''.join(s))
print('ok')
