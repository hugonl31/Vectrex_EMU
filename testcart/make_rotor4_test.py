# make_rotor4_test.py - writes rotor4_test.asm: three helicopter-like test objects flying sideways (1 step per frame):
# a still body (a box with a tail) and on top of it a rotor of four pizza-slice blades spinning at 2, 5 and 9 / 64 turns
# per frame - for checking the afterglow of fast-turning, overlapping lines (Armor Attack's helicopter).
# Build: lwasm --format=raw -o rotor4_test_raw.bin rotor4_test.asm, then pad to 32768 bytes with $FF.
import math, os

R, W = 60, 3                                   # blade length (at scale $30), blade width (steps of 64)
def tip(i):
    a = 2 * math.pi * (i % 64) / 64
    return round(R * math.sin(a)), round(R * math.cos(a))

ROTORS = [((40, -70), 2), ((40, 70), 5), ((-55, 0), 9)]   # (centre y, x at scale $7F), steps per frame
BODY = [('m', -12, -35), ('d', 0, 70), ('d', 24, 0), ('d', 0, -70), ('d', -24, 0),   # the box round the hub
        ('m', 12, 0), ('d', 0, -60), ('d', 10, -10), ('m', -10, 105)]                 # the tail; back to the hub

s = []
w = s.append
w("""; rotor4_test.asm - generated by make_rotor4_test.py: three helicopters flying sideways, a still body and four
; pizza-slice blades on top spinning at 2, 5 and 9 / 64 turns per frame.
; Build: lwasm --format=raw -o rotor4_test_raw.bin rotor4_test.asm, then pad to 32768 bytes with $FF.

Wait_Recal      equ $F192
Intensity_a     equ $F2AB
Moveto_d        equ $F312
Draw_Line_d     equ $F3DF
Reset0Ref       equ $F354
Vec_Misc_Count  equ $C823

Angles          equ $C880           ; one byte per rotor
Blade           equ $C884           ; the blade's angle now
Count           equ $C885
Pos             equ $C888           ; the helicopters' sideways place, moving 1 per frame

        org     $0000
        fcc     "g GCE 2026"
        fcb     $80
        fdb     $FD0D
        fcb     $F8,$50,$20,-$40
        fcc     "ROTOR TEST 4"
        fcb     $80
        fcb     0

Start:
        clr     Angles
        clr     Angles+1
        clr     Angles+2
        clr     Pos
Main:
        jsr     Wait_Recal
        lda     #$7F
        jsr     Intensity_a
        inc     Pos
""")
for k, ((cy, cx), sp) in enumerate(ROTORS):
    w("""; helicopter %d
        jsr     Reset0Ref
        lda     #$7F
        sta     $D004
        lda     #%d
        ldb     #%d
        addb    Pos
        jsr     Moveto_d
        lda     #$30
        sta     $D004
        jsr     Body
        lda     Angles+%d
        adda    #%d
        anda    #63
        sta     Angles+%d
        sta     Blade
        lda     #4
        sta     Count
        jsr     Rotor
""" % (k, cy, cx, k, sp, k))
w("""        jmp     >Main               ; (extended: Main sits below $100 and DP is $D0)

; the still body from the hub, back to the hub
Body:
""")
for op, y, x in BODY:
    if op == 'm':
        w("        lda     #%d\n        ldb     #%d\n        jsr     Moveto_d\n" % (y, x))
    else:
        w("        lda     #%d\n        ldb     #%d\n        clr     Vec_Misc_Count\n        jsr     Draw_Line_d\n" % (y, x))
w("""        rts

; four pizza-slice blades from the hub: out along one side, across the tip, back along the other side
Rotor:
        lda     Blade
        lsla
        ldx     #Side1
        leax    a,x
        ldd     ,x
        clr     Vec_Misc_Count
        jsr     Draw_Line_d
        lda     Blade
        lsla
        ldx     #Edge
        leax    a,x
        ldd     ,x
        clr     Vec_Misc_Count
        jsr     Draw_Line_d
        lda     Blade
        lsla
        ldx     #Side2
        leax    a,x
        ldd     ,x
        clr     Vec_Misc_Count
        jsr     Draw_Line_d
        lda     Blade
        adda    #16
        anda    #63
        sta     Blade
        dec     Count
        bne     Rotor
        rts

""")
def table(name, f):
    w(name + ":\n")
    for i in range(64):
        y, x = f(i)
        w("        fcb     %d,%d\n" % (y, x))
table("Side1", tip)
table("Edge", lambda i: (tip(i + W)[0] - tip(i)[0], tip(i + W)[1] - tip(i)[1]))
table("Side2", lambda i: (-tip(i + W)[0], -tip(i + W)[1]))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rotor4_test.asm'), 'w', newline='\n').write(''.join(s))
print('ok')
