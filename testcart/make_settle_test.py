"""make_settle_test.py - writes settle_test.asm: the beam switch against the spot. A line drawn by hand (RAMP and /BLANK
written to the cycle); only ONE thing varies per row - when the beam goes off after the stop, or on around the start -
so where the lit line ends (or begins) is where the spot was at that moment: the spot's settling curve, and the beam
switch's own delay. Buttons 1-4 pick the page; every page runs at 50 Hz. README.md has the table.

Page 1  OFF     a line (beam on 12 cycles before RAMP on: a dot marks the start), RAMP off after L cycles, the beam OFF K
                cycles after RAMP off, K per row (top to bottom). Left column speed $50 (L 40), right $7F (L 24).
Page 2  ON      the same line, the beam ON K cycles after RAMP on, off 40 cycles after RAMP off (a dot marks the end).
                Left column speed $50 (L 48), right $7F (L 40).
Page 3  PULSE   RAMP on throughout, the beam pulsed: row 1 lit for N cycles (dark 16 between), row 2 dark for N cycles in a
                lit line, speed $40; rows 3-4 the same at $7F - the dash's length = (N + off delay - on delay) x speed.
Page 4  Y       pages 1 and 2 for a vertical line (the Y speed from its hold, X 0), speed $50: 11 lines OFF, then 10 ON.
"""
import os
import make_dot_test as D
from make_dot_test import delay, b8, text, row_start, hand_on, hand_off, set_y, w, A
from make_switch_test import Sched, STX, STY, STAC, STBC

OFF_K = [-12, -8, -5, 5, 8, 12, 16, 20, 24, 32, 48]         # (0 cannot be: two writes in one cycle; +-5 the nearest)
ON_K = [-12, -8, -4, 5, 8, 12, 16, 20, 24, 32]
P1_COLS = [(0x50, 40, -0x68), (0x7F, 24, 0x08)]             # speed, cycles, x
P2_COLS = [(0x50, 48, -0x70), (0x7F, 40, -0x08)]
ROW_Y0, ROW_DY = 0x58, 0x10
PULSE_N = [4, 6, 7, 8, 12, 16]
PULSE_N7 = [4, 8, 16]
P3_ROWS = [(0x40, PULSE_N, True, 0x40), (0x40, PULSE_N, False, 0x20), (0x7F, PULSE_N7, True, -0x08), (0x7F, PULSE_N7, False, -0x28)]   # speed, pulses, lit pulses?, y
P3_X0 = -0x70
P4_V, P4_L, P4_Y0, P4_X0, P4_DX = 0x50, 40, 0x48, -0x74, 0x0B

def run(events):
    """events: (time of the VIA write, op) - emitted in time order, each write on its cycle"""
    s = Sched()
    for t, op in sorted(events, key=lambda e: e[0]): s.write(*op, t)
    return s

def line(v, L, k_off=None, k_on=None, vertical=False):
    """one hand-drawn line: RAMP on at 20, off at 20 + L; the beam on at 8 (or 20 + k_on), off at 20 + L + 40 (or + k_off)"""
    hand_on()
    if vertical:
        set_y(-v); w('        clr     <$01                ; DAC 0: the X speed'); w('        ldx     #$0100'); w('        ldy     #$8100')
    else:
        set_y(0); w('        ldx     #$01%02X' % v); w('        ldy     #$81%02X' % v)
    w('        lda     #$EE'); w('        ldb     #$CE')
    t_on = 20; t_off = t_on + L
    ev = [(t_on, STX), (t_off, STY), (8 if k_on is None else t_on + k_on, STAC), (t_off + (40 if k_off is None else k_off), STBC)]
    run(ev); hand_off()

def emit_page1():
    for v, L, x in P1_COLS:
        for i, k in enumerate(OFF_K):
            w('; OFF: speed $%02X, %d cycles; the beam off %+d cycles after RAMP off' % (v, L, k))
            row_start(0x7F, ROW_Y0 - i * ROW_DY, x); line(v, L, k_off=k)

def emit_page2():
    for v, L, x in P2_COLS:
        for i, k in enumerate(ON_K):
            w('; ON: speed $%02X, %d cycles; the beam on %+d cycles after RAMP on' % (v, L, k))
            row_start(0x7F, ROW_Y0 - i * ROW_DY, x); line(v, L, k_on=k)

def emit_page3():
    for v, NS, lit, y in P3_ROWS:
        w('; PULSE: speed $%02X, %s for N = %s cycles' % (v, 'lit' if lit else 'dark', NS))
        row_start(0x7F, y, P3_X0); hand_on(); set_y(0)
        w('        ldx     #$01%02X' % v); w('        ldy     #$81%02X' % v); w('        lda     #$EE'); w('        ldb     #$CE')
        ev = [(10, STX)]; t = 34
        if not lit: ev.append((18, STAC))
        for n in NS:
            ev.append((t, STAC if lit else STBC)); ev.append((t + n, STBC if lit else STAC)); t += n + 16
        ev.append((t + 4, STY))
        if not lit: ev.append((t + 12, STBC))
        run(ev); hand_off()

def emit_page4():
    for i, k in enumerate(OFF_K):
        w('; Y OFF: the beam off %+d cycles after RAMP off' % k)
        row_start(0x7F, P4_Y0, P4_X0 + i * P4_DX); line(P4_V, P4_L, k_off=k, vertical=True)
    for i, k in enumerate(ON_K):
        w('; Y ON: the beam on %+d cycles after RAMP on' % k)
        row_start(0x7F, P4_Y0, P4_X0 + (len(OFF_K) + 1 + i) * P4_DX); line(P4_V, P4_L, k_on=k, vertical=True)

