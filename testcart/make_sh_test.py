"""make_sh_test.py - writes sh_test.asm: one page testing the Y sample-and-hold's settling.

The DAC (port A) reaches the Y integrator through a sample-and-hold capacitor, connected while the
multiplexer is enabled (port B bit 0 low, channel 0 = Y). Each dot: the hold is first charged to a far
value P for 40 cycles, then set to the target T with the multiplexer open for only d cycles, then the
beam moves out (Y from the hold, X straight from the DAC) and a dot is drawn. Top row: P = -$7F,
T = +$40; bottom row: P = +$7F, T = -$40. Dim marks at both ends of each row show the target (drawn by the BIOS);
d under each column. A dot short of its line: the hold did not settle in d cycles.
"""
import os

def delay(n):
    """exactly n cycles (n = 0 or n >= 2): NOP = 2, BRN = 3"""
    if n == 0:
        return []
    assert n >= 2
    out = []
    if n % 2:
        out.append('        brn     *')
        n -= 3
    out += ['        nop'] * (n // 2)
    return out

DS = [4, 6, 7, 8, 9, 10, 12, 16, 24, 40]      # multiplexer-on cycles (STA on ... STB off = D + 4)
XS = [-0x5E + 0x15 * k for k in range(len(DS))]
ROWS = [(-0x7F, 0x40), (0x7F, -0x40)]          # (P, T)
SCALE = 0x7F

A = []
w = A.append
w('; sh_test.asm - generated by make_sh_test.py: the Y sample-and-hold settling time, one page.')
w('; Build: lwasm --format=raw -o sh_test_raw.bin sh_test.asm, then pad to 32768 bytes with $FF.')
w('')
w('Wait_Recal      equ $F192')
w('Intensity_a     equ $F2AB')
w('Dot_here        equ $F2C5')
w('Moveto_d        equ $F312')
w('Reset0Ref       equ $F354')
w('Print_Str_d     equ $F37A')
w('Draw_Line_d     equ $F3DF')
w('Vec_Dot_Dwell   equ $C828')
w('Vec_Text_HW     equ $C82A')
w('VIA_t1_cnt_lo   equ $D004')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "S+H TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('Main:')
w('        jsr     Wait_Recal')
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
w('        lda     #$40')
w('        jsr     Intensity_a')
for P, T in ROWS:                               # the reference marks at the targets (dim)
    for xs in (-0x7F, 0x6F):                    # short marks at both ends (the dots stay visible)
        w('        jsr     Reset0Ref')
        w('        lda     #$%02X' % SCALE)
        w('        sta     <$04')
        w('        ldd     #$%04X' % (((T & 0xff) << 8) | (xs & 0xff)))
        w('        jsr     Moveto_d')
        w('        ldd     #$0010')
        w('        jsr     Draw_Line_d')
w('        lda     #$7F')
w('        jsr     Intensity_a')
w('        lda     #$20')
w('        sta     Vec_Dot_Dwell')
w('        jsr     Reset0Ref')
for P, T in ROWS:
    for d, x in zip(DS, XS):
        w('        lda     #$CC                ; d = %d, P = %d, T = %d: zero the integrators (beam to centre, dark)' % (d, P, T))
        w('        sta     <$0C')
        w('        lda     #$%02X' % (P & 0xff))  # the hold to P (40 cycles)
        w('        sta     <$01')
        w('        clr     <$00')
        A.extend(delay(40))
        w('        ldb     #1')
        w('        stb     <$00')
        w('        lda     #$%02X' % (T & 0xff))  # to T for d cycles
        w('        sta     <$01')
        w('        lda     #0')
        w('        ldb     #1')
        w('        sta     <$00               ; multiplexer on (Y)')
        A.extend(delay(d - 4))
        w('        stb     <$00               ; off: d cycles later')
        w('        lda     #$CE                ; zeroing off')
        w('        sta     <$0C')
        w('        lda     #$%02X' % (x & 0xff))  # X straight from the DAC, the move
        w('        sta     <$01')
        w('        lda     #$%02X' % SCALE)
        w('        sta     <$04')
        w('        clr     <$05')
        w('        lda     #$40')
        w('@w%d_%d   bita    <$0D' % (d, P & 0xff))
        w('        beq     @w%d_%d' % (d, P & 0xff))
        w('        jsr     Dot_here')
w('        ldd     #$F830')                    # the labels
w('        std     Vec_Text_HW')
for k, (d, x) in enumerate(zip(DS, XS)):
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        sta     <$04')
    w('        ldu     #Lab%d' % k)
    w('        ldd     #$%04X' % (((-0x70) & 0xff) << 8 | ((x - 6) & 0xff)))
    w('        jsr     Print_Str_d')
w('        jmp     Main')
w('')
for k, d in enumerate(DS):
    w('Lab%d    fcc     "%2d"' % (k, d))
    w('        fcb     $80')

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sh_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote sh_test.asm')
