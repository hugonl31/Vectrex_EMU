"""make_shapes_test.py - writes shapes_test.asm ("SHAPES TEST"): standing shapes drawn with the BIOS's own routines, as a
game draws them - for a photo next to a render, no moment to catch. Buttons 1-4; 50 Hz.

Page 1  VLC      four shapes (arrowhead, octagon, square, zigzag: rows) drawn with Draw_VLc at scales $08, $10, $20,
                 $30 (columns): short vectors with the BIOS's own pauses at the corners.
Page 2  VLP      the same with Draw_VLp (the routine Mine Storm draws its ship and mines with).
Page 3  PATTERN  the octagon and the zigzag with Draw_VLp and the patterns $AA, $F0, $E7 (rows) at scales $20 and $30:
                 dotted and dashed lines.
Page 4  TEXT     the BIOS's text at four sizes (Vec_Text_HW: height / width $FC/$30, $F8/$50, $F4/$60, $F0/$78).
"""
from tc_common import *

SHAPES = [('Arrow', [(0x7F, 0x30), (-0x7F, 0x30), (0x30, -0x30), (-0x30, -0x30)]),
          ('Octa', [(0x28, 0x14), (0x14, 0x28), (-0x14, 0x28), (-0x28, 0x14), (-0x28, -0x14), (-0x14, -0x28), (0x14, -0x28), (0x28, -0x14)]),
          ('Square', [(0x60, 0), (0, 0x60), (-0x60, 0), (0, -0x60)]),
          ('Zig', [(0x60, 0x10), (-0x60, 0x10), (0x60, 0x10), (-0x60, 0x10), (0x60, 0x10), (-0x60, 0x10)])]
SCALES = [0x08, 0x10, 0x20, 0x30]
COL_X = [-0x74, -0x60, -0x38, 0x08]
ROW_Y = [0x38, 0x10, -0x34, -0x60]

def place(z, y, x, s):
    w('        jsr     Reset0Ref'); w('        lda     #$%02X' % z); w('        jsr     Intensity_a'); w('        lda     #$7F'); w('        sta     <$04')
    w('        ldd     #$%02X%02X' % (b8(y), b8(x))); w('        jsr     Moveto_d'); w('        lda     #$%02X' % s); w('        sta     <$04                ; scale')

def build():
    begin('SHAPES TEST', 'shapes_test.asm - generated by make_shapes_test.py: standing shapes by the BIOS routines; buttons 1-4.')
    page(1)
    for r, (name, _) in enumerate(SHAPES):
        for c, s in enumerate(SCALES):
            place(0x7F, ROW_Y[r], COL_X[c], s); w('        ldx     #C%s' % name); w('        jsr     Draw_VLc')
    text('L1', 0x70, -0x70); text('T1', -0x74, -0x50); page_end()
    page(2)
    for r, (name, _) in enumerate(SHAPES):
        for c, s in enumerate(SCALES):
            place(0x7F, ROW_Y[r], COL_X[c], s); w('        ldx     #P%sFF' % name); w('        jsr     Draw_VLp')
    text('L2', 0x70, -0x70); text('T2', -0x74, -0x50); page_end()
    page(3)
    for r, pat in enumerate((0xAA, 0xF0, 0xE7)):
        for c, (name, s) in enumerate((('Octa', 0x20), ('Octa', 0x30), ('Zig', 0x20), ('Zig', 0x30))):
            place(0x7F, 0x28 - r * 0x38, (-0x70, -0x48, 0x00, 0x30)[c], s); w('        ldx     #P%s%02X' % (name, pat)); w('        jsr     Draw_VLp')
    text('L3', 0x70, -0x70); text('T3', -0x74, -0x50); page_end()
    page(4)
    for i, (h, wd) in enumerate(((0xFC, 0x30), (0xF8, 0x50), (0xF4, 0x60), (0xF0, 0x78))):
        w('        ldd     #$%02X%02X' % (h, wd)); w('        std     Vec_Text_HW'); w('        jsr     Reset0Ref'); w('        lda     #$7F'); w('        jsr     Intensity_a')
        w('        lda     #$7F'); w('        sta     <$04'); w('        ldu     #Txt'); w('        ldd     #$%02X%02X' % (b8(0x50 - i * 0x28), b8(-0x70))); w('        jsr     Print_Str_d')
    text('T4', -0x74, -0x50); page_end()
    w('')
    for name, v in SHAPES:
        w('C%s:  fcb     %d' % (name, len(v) - 1))
        for dy, dx in v: w('        fcb     $%02X,$%02X' % (b8(dy), b8(dx)))
    for name, v in SHAPES:
        for pat in (0xFF, 0xAA, 0xF0, 0xE7):
            if pat != 0xFF and name not in ('Octa', 'Zig'): continue
            w('P%s%02X:' % (name, pat))
            for dy, dx in v: w('        fcb     $%02X,$%02X,$%02X' % (pat, b8(dy), b8(dx)))
            w('        fcb     $01')
    string('L1', 'DRAW VLC  SCALE 08 10 20 30'); string('T1', '1 VLC')
    string('L2', 'DRAW VLP  SCALE 08 10 20 30'); string('T2', '2 VLP')
    string('L3', 'PATTERN AA F0 E7'); string('T3', '3 PATTERN')
    string('Txt', 'VECTREX 0123'); string('T4', '4 TEXT')
    finish('shapes_test', 'Shapes Test')

if __name__ == '__main__':
    build()
