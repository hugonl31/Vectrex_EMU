"""make_ship_test.py - the Ship Test cartridge: Mine Storm's mothership crossing the screen from top to bottom while it
shrinks, over and over - the same every pass, for Smooth motion's tests (a shape of many strokes that moves and changes
size; in the game it comes once, and never at the same moment).

    python make_ship_test.py          ->  ship_test.asm (the ship's strokes from ship_strokes.json)
    python make_ship_test.py --pack   ->  ship_test.bin (32 KB), ship_test_64k.bin from ship_test_raw.bin

ship_strokes.json: the ship as the emulator drew it in Mine Storm, each stroke's two ends in emulator units (taken once
from a frame of the game: tools - the PC app's line list; kept so the cart builds without the game running)."""
import sys, os, json
here = os.path.dirname(os.path.abspath(__file__))
G = 64.0                                             # emulator units a list step (the longest stroke: 70 steps)
if '--pack' in sys.argv:
    raw = open(os.path.join(here, 'ship_test_raw.bin'), 'rb').read()
    img = raw + b'\xff' * (32768 - len(raw))
    open(os.path.join(here, 'ship_test.bin'), 'wb').write(img)
    open(os.path.join(here, 'ship_test_64k.bin'), 'wb').write(img + img)
    print('packed', len(raw), 'bytes of code')
    sys.exit(0)
S = json.load(open(os.path.join(here, 'ship_strokes.json')))        # [[x0, y0, x1, y1], ...] in the order drawn
xs = [p for s in S for p in (s[0], s[2])]; ys = [p for s in S for p in (s[1], s[3])]
cx = (min(xs) + max(xs)) / 2.0; cy = (min(ys) + max(ys)) / 2.0
q = lambda x, y: (int(round((x - cx) / G)), -int(round((y - cy) / G)))   # (the emulator's y runs down the screen, the Vectrex's up)
out = []; cur = (0, 0)
def move(to):
    global cur
    dx, dy = to[0] - cur[0], to[1] - cur[1]
    while dx or dy:                                   # (a step is at most 127)
        sx = max(-127, min(127, dx)); sy = max(-127, min(127, dy))
        out.append('        fcb     0,%d,%d' % (sy, sx)); dx -= sx; dy -= sy
    cur = to
for x0, y0, x1, y1 in S:
    a, b = q(x0, y0), q(x1, y1)
    if a != cur: move(a)
    dx, dy = b[0] - a[0], b[1] - a[1]
    if not (dx or dy): continue
    assert abs(dx) <= 127 and abs(dy) <= 127
    out.append('        fcb     $FF,%d,%d' % (dy, dx)); cur = b
out.append('        fcb     1')
asm = r"""; ship_test.asm - Ship Test: Mine Storm's mothership crossing the screen from top to bottom while it shrinks, over and
; over - the same every pass. For Smooth motion's tests: a shape of many strokes that moves and changes size.
; Generated by make_ship_test.py (the ship's strokes: ship_strokes.json). Build: build_cart.sh ship_test "Ship Test"

Wait_Recal      equ $F192
Intensity_a     equ $F2AB
Moveto_d        equ $F312
Reset0Ref       equ $F354
Draw_Line_d     equ $F3DF
Scale           equ $C880
Ypos            equ $C881
Tick            equ $C882
SMAX            equ 72                  ; the ship's scale at the top
YTOP            equ 96                  ; where it starts (at scale $7F), and -YTOP where it ends

        org     $0000
        fcc     "g GCE 2026"
        fcb     $80
        fdb     $FD0D
        fcb     $F8,$50,$20,-$48
        fcc     "SHIP TEST"
        fcb     $80
        fcb     0

Start:
        lda     #SMAX
        sta     Scale
        lda     #YTOP
        sta     Ypos
        clr     Tick
Main:
        jsr     Wait_Recal
        lda     #$5F
        jsr     Intensity_a
        jsr     Reset0Ref
        lda     #$7F                    ; to the ship's place, at full scale
        sta     <$04
        lda     Ypos
        clrb
        jsr     Moveto_d
        lda     Scale                   ; the ship, at its scale
        sta     <$04
        ldx     #Ship
Next    lda     ,x+
        beq     Mv
        bmi     Dr
        bra     Step
Mv      lda     ,x+
        ldb     ,x+
        pshs    x
        jsr     Moveto_d
        puls    x
        bra     Next
Dr      lda     ,x+
        ldb     ,x+
        pshs    x
        jsr     Draw_Line_d
        puls    x
        bra     Next
Step    dec     Ypos                    ; a step down every frame, smaller every third
        inc     Tick
        lda     Tick
        cmpa    #3
        blo     Chk
        clr     Tick
        dec     Scale
Chk     lda     Ypos
        cmpa    #-YTOP
        bgt     Main
        bra     Start

Ship:                                   ; flag (0 move, $FF draw, 1 end), y, x
""" + '\n'.join(out) + '\n'
open(os.path.join(here, 'ship_test.asm'), 'w', newline='\n').write(asm)
print('ship_test.asm: %d strokes, %d list entries' % (len(S), len(out) - 1))
