"""make_short_test.py - writes short_test.asm ("SHORT TEST"): does a short move settle as a long one? The Settle Test's
lines again, but with ramps as short as the BIOS's pieces at small scales (6 - 13 cycles), and one page with the same
ramp at four speeds (the move's size alone). Buttons 1-4 pick the page; 50 Hz. Every write on its cycle.

Page 1  SHORT OFF  hand RAMP of L = 6, 8, 10, 13 cycles (columns, left to right) at speed $7F; the beam on 12 cycles before
                   RAMP on, OFF K cycles after RAMP off (rows, top to bottom).
Page 2  SHORT ON   the same ramps; the beam ON K cycles after RAMP on, off 40 cycles after RAMP off.
Page 3  T1 SHORT   RAMP by timer 1 (N = 6, 8, 10, 13), the beam by PCR: OFF K cycles after t0 + N.
Page 4  SIZE       hand RAMP of 12 cycles at speeds $20, $40, $60, $7F (columns); the beam OFF K cycles after RAMP off.
The K of every row is in the listing's comments and in README.md (the nearest the writes allow to 5, 8, 12 ... per column).
"""
import os
import make_dot_test as D
from make_dot_test import delay, b8, text, row_start, hand_off, w, A
from make_settle_test import line
from make_timer_test import t1_line

COL_X = [-0x70, -0x38, 0x00, 0x38]
SHORT_L = [6, 8, 10, 13]
SIZE_V = [0x20, 0x40, 0x60, 0x7F]
ROW_Y0, ROW_DY = 0x58, 0x14
WANT_OFF = [5, 8, 12, 16, 20, 24, 32, 48]
WANT_ON = [-8, 5, 8, 12, 16, 20, 24, 32]
TABLE = {}                                                  # page -> column -> the Ks used

def try_line(fn, want, used):
    """the K nearest to `want` that the writes allow and the column has not yet (the generator asserts when two writes collide)"""
    for d in sorted(range(-6, 14), key=lambda d: (abs(d), -d)):
        if want + d in used: continue
        n = len(A)
        try:
            fn(k=want + d); return want + d
        except AssertionError:
            del A[n:]
    raise SystemExit('no room near K = %d' % want)

def emit(page, cols, wants, fn):
    TABLE[page] = []
    for ci, col in enumerate(cols):
        ks = []
        for i, k in enumerate(wants):
            w('; page %d, column %d, row %d' % (page, ci + 1, i + 1))
            row_start(0x7F, ROW_Y0 - i * ROW_DY, COL_X[ci])
            ks.append(try_line(lambda k, c=col: fn(c, k), k, ks))
        TABLE[page].append(ks)

