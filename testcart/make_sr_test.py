"""make_sr_test.py - writes sr_test.asm ("SR TEST"): the shift register's switching after its bits have gone out, and the
BIOS's own Draw_VLp on one vector. Button 4 the next page, button 1 the one before; the page's number in its title.

Page 1  SR GAP EVEN  as the Photo Test's page 5 (RAMP on 114 cycles, speed $7F; the shift register $FF at cycle 30, $00
                     written G cycles later, $00 again 24 after): G = 18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 40, 44, 48,
                     54, 60 (rows).
Page 2  SR GAP ODD   G = 19, 21, 23 .. 47.
Page 3  VLP 6-20     ONE vector drawn by the BIOS's Draw_VLp (pattern $FF, speed $7F to the right), scale N = 6 .. 20 a
                     row: the line the BIOS really lights, its start dot, its end.
Page 4  VLP 21-35    N = 21 .. 35.
"""
from tc_common import *
from make_settle_test import run
from make_switch_test import STX, STY
from make_timer_test import STASR, STBSR
from make_bios_test import sr_setup

EVEN = [18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 40, 44, 48, 54, 60]
ODD = list(range(19, 48, 2))
X0 = -0x70

def sr_gap(g):
    sr_setup(0x7F); w('        lda     #$FF'); w('        clrb')
    run([(10, STX), (30, STASR), (30 + g, STBSR), (54 + g, STBSR), (124, STY)]); hand_off()

def vlp(n, y):
    w('        jsr     Reset0Ref'); w('        lda     #$7F'); w('        jsr     Intensity_a'); w('        lda     #$7F'); w('        sta     <$04')
    w('        ldd     #$%02X%02X' % (b8(y), b8(X0))); w('        jsr     Moveto_d'); w('        lda     #%d' % n); w('        sta     <$04                ; scale %d' % n)
    w('        ldx     #OneVec'); w('        jsr     Draw_VLp')

def build():
    begin_paged('SR TEST', 'sr_test.asm - generated by make_sr_test.py: the shift register after its bits; Draw_VLp on one vector; buttons 4 / 1.', 4)
    for p, gs in ((1, EVEN), (2, ODD)):
        ppage(p)
        for i, g in enumerate(gs):
            w('; SR gap %d' % g); row_start(0x7F, 0x60 - i * 0x0C, X0); sr_gap(g)
        text('L%d' % p, 0x70, -0x70); text('T%d' % p, -0x74, -0x50); page_end()
    for p, n0 in ((3, 6), (4, 21)):
        ppage(p)
        for i in range(15): vlp(n0 + i, 0x60 - i * 0x0C)
        text('L%d' % p, 0x70, -0x70); text('T%d' % p, -0x74, -0x50); page_end()
    page_table(4)
    w('OneVec: fcb     $FF,$00,$7F'); w('        fcb     $01')
    string('L1', 'SR OFF AFTER 18 TO 60 EVEN'); string('T1', '01/04 SR GAP EVEN')
    string('L2', 'SR OFF AFTER 19 TO 47 ODD'); string('T2', '02/04 SR GAP ODD')
    string('L3', 'BIOS DRAW VLP  SCALE 6 TO 20'); string('T3', '03/04 VLP 6-20')
    string('L4', 'BIOS DRAW VLP  SCALE 21 TO 35'); string('T4', '04/04 VLP 21-35')
    finish('sr_test', 'SR Test')

if __name__ == '__main__':
    build()
