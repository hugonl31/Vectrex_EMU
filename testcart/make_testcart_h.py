"""libretro/testcart.h from testcart/test_cart.bin: the Test Cart the phone apps carry and write into roms/Tests (the picture
compared between platforms). Run after test_cart.asm is assembled and packed."""
import os
here = os.path.dirname(os.path.abspath(__file__))
d = open(os.path.join(here, 'test_cart.bin'), 'rb').read().rstrip(b'\xff')
L = ['/* testcart.h - generated by testcart/make_testcart_h.py from test_cart.bin: the Test Cart (pages: trail, levels, dots,',
     ' * corners), written by the apps into roms/Tests so every platform shows the same cartridge. */',
     '#include <stdio.h>', '#include <string.h>',
     'static const unsigned char VX_TESTCART[%d] = {' % len(d)]
for i in range(0, len(d), 24):
    L.append('\t' + ','.join('%d' % b for b in d[i:i + 24]) + ',')
L += ['};',
      '/* the file made (32 KB, padded with $FF) unless it is there with this content */',
      'static void vx_testcart_write (const char *path)',
      '{',
      '\tstatic unsigned char im[32768], old[32768]; memset (im, 0xFF, sizeof im); memcpy (im, VX_TESTCART, sizeof VX_TESTCART);',
      '\tFILE *f = fopen (path, "rb"); if (f) { size_t n = fread (old, 1, sizeof old, f); fclose (f); if (n == sizeof old && !memcmp (old, im, sizeof im)) return; }',
      '\tf = fopen (path, "wb"); if (f) { fwrite (im, 1, sizeof im, f); fclose (f); }',
      '}', '']
open(os.path.join(here, '..', 'libretro', 'testcart.h'), 'w', newline='\n').write('\n'.join(L))
print('wrote libretro/testcart.h', len(d))
