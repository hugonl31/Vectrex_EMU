    if '--pack' in os.sys.argv:
        raw = open(os.path.join(here, 'timer_test2_raw.bin'), 'rb').read(); assert len(raw) <= 32768, len(raw)
        img = raw + b'\xFF' * (32768 - len(raw))
        open(os.path.join(here, 'timer_test2.bin'), 'wb').write(img); open(os.path.join(here, 'timer_test2_64k.bin'), 'wb').write(img * 2)
        os.remove(os.path.join(here, 'timer_test2_raw.bin')); print('packed timer_test2.bin (32 KB, %d used), timer_test2_64k.bin' % len(raw))
    else:
        open(os.path.join(here, 'timer_test2.asm'), 'w', newline='\n').write('\n'.join(A) + '\n'); print('wrote timer_test2.asm')
