"""make_timer_test.py - writes timer_test2.asm ("TIMER TEST"): the Settle Test's two questions asked of the BIOS's own
means - RAMP switched by timer 1 (one-shot, PB7) and the beam switched by the shift register - one of them at a time
against the hand-timed other, so each one's own lateness shows. Buttons 1-4 pick the page; 50 Hz.

Page 1  T1 OFF   RAMP by timer 1 (N = 40 at speed $50, 24 at $7F; started at t0), the beam by PCR: on 12 cycles before t0,
                 OFF K cycles after t0 + N. As the Settle Test's page 1 but for the RAMP's switch.
Page 2  T1 ON    RAMP by timer 1 (N = 48 / 40), the beam by PCR: ON K cycles after t0, off 40 after t0 + N.
Page 3  SR OFF   RAMP by hand (as the Settle Test), the beam by the shift register: $FF written 12 cycles before RAMP on,
                 $00 written K cycles after RAMP off.
Page 4  SR ON    RAMP by hand, the shift register: $FF written K cycles after RAMP on, $00 written 40 after RAMP off.
"""
import os
import make_dot_test as D
from make_dot_test import delay, b8, text, row_start, hand_off, set_y, w, A
from make_switch_test import Sched, STX, STY, STAC, STBC
from make_settle_test import run, ROW_Y0, ROW_DY

OFF_K = [-12, -8, -5, 5, 8, 12, 16, 20, 24, 32, 48]
ON_K_T1 = [-12, -8, 4, 8, 12, 16, 20, 24, 32]               # (the timer's start takes cycles 15-20: 4 the nearest after)
ON_K = [-12, -8, -4, 5, 8, 12, 16, 20, 24, 32]
OFF_COLS = [(0x50, 40, -0x68), (0x7F, 24, 0x08)]            # speed, cycles, x
ON_COLS = [(0x50, 48, -0x70), (0x7F, 40, -0x08)]
STT1 = ('clr     <$05', 6, 6)                               # timer 1's high counter: the one-shot starts (the write in cycle 6)
STASR, STBSR = ('sta     <$0A', 4, 4), ('stb     <$0A', 4, 4)

def t1_line(v, N, k_off=None, k_on=None):
    """RAMP by timer 1 (PB7), the beam by PCR; t0 = 20: the write that starts the timer"""
    w('        lda     #$81'); w('        sta     <$00                ; mux off')
    w('        lda     #$80'); w('        sta     <$0B                ; ACR: PB7 = timer 1 (one-shot), /BLANK by PCR')
    set_y(0)
    w('        lda     #$%02X' % v); w('        sta     <$01                ; the X speed'); w('        lda     #$%02X' % N); w('        sta     <$04                ; timer 1: %d cycles' % N)
    w('        lda     #$EE'); w('        ldb     #$CE')
    t0 = 20
    run([(t0, STT1), (8 if k_on is None else t0 + k_on, STAC), (t0 + N + (40 if k_off is None else k_off), STBC)])
    w('        clr     <$01                ; the X speed 0'); hand_off()

def sr_line(v, L, k_off=None, k_on=None):
    """RAMP by hand, the beam by the shift register ($FF / $00 written); RAMP on at 20, off at 20 + L"""
    w('        lda     #$81'); w('        sta     <$00                ; ramp off, mux off')
    w('        lda     #$18'); w('        sta     <$0B                ; ACR: RAMP by hand, /BLANK = the shift register')
    w('        clr     <$0A                ; the shift register 0: dark')
    set_y(0)
    w('        ldx     #$01%02X' % v); w('        ldy     #$81%02X' % v); w('        lda     #$FF'); w('        clrb')
    t_on = 20; t_off = t_on + L
    run([(t_on, STX), (t_off, STY), (8 if k_on is None else t_on + k_on, STASR), (t_off + (40 if k_off is None else k_off), STBSR)])
    hand_off()

def emit(fn, cols, ks, off):
    for v, L, x in cols:
        for i, k in enumerate(ks):
            w('; %s: speed $%02X, %d cycles, K %+d' % (fn.__name__, v, L, k))
            row_start(0x7F, ROW_Y0 - i * ROW_DY, x)
            if off: fn(v, L, k_off=k)
            else: fn(v, L, k_on=k)

if __name__ == '__main__':
    del A[:]
    w('; timer_test2.asm - generated by make_timer_test.py: timer 1 and the shift register against the hand-timed switch; buttons 1-4.')
    w('')
    for n, a in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Moveto_d', 0xF312), ('Reset0Ref', 0xF354),
                 ('Print_Str_d', 0xF37A), ('Vec_Btn_State', 0xC80F), ('Vec_Text_HW', 0xC82A), ('Page', 0xC880)):
        w('%-15s equ $%04X' % (n, a))
    w('')
    w('        org     $0000'); w('        fcc     "g GCE 2026"'); w('        fcb     $80'); w('        fdb     $FD0D')
    w('        fcb     $F8,$50,$20,-$40'); w('        fcc     "TIMER TEST"'); w('        fcb     $80'); w('        fcb     0')
    w('')
    w('Start:  clr     Page')
    w('Main:   jsr     Wait_Recal'); w('        lda     #$D0'); w('        tfr     a,dp'); w('        setdp   $D0')
    w('        jsr     Read_Btns'); w('        lda     Vec_Btn_State')
    for i in range(4):
        w('        bita    #$%02X' % (1 << i)); w('        beq     NoB%d' % i); w('        ldb     #%d' % i); w('        stb     Page'); w('NoB%d:' % i)
    w('        ldb     Page'); w('        lbeq    Page1'); w('        decb'); w('        lbeq    Page2'); w('        decb'); w('        lbeq    Page3'); w('        lbra    Page4')
    w(''); w('Page1:'); emit(t1_line, OFF_COLS, OFF_K, True); text('L1', 0x70, -0x70); text('T1', -0x70, -0x50); w('        lbra    Main')
    w(''); w('Page2:'); emit(t1_line, ON_COLS, ON_K_T1, False); text('L2', 0x70, -0x70); text('T2', -0x70, -0x50); w('        lbra    Main')
    w(''); w('Page3:'); emit(sr_line, OFF_COLS, OFF_K, True); text('L3', 0x70, -0x70); text('T3', -0x70, -0x50); w('        lbra    Main')
    w(''); w('Page4:'); emit(sr_line, ON_COLS, ON_K, False); text('L4', 0x70, -0x70); text('T4', -0x70, -0x50); w('        lbra    Main')
    w('')
    def s(label, t):
        w('%-7s fcc     "%s"' % (label, t)); w('        fcb     $80')
    s('L1', 'TIMER RAMP  BEAM OFF %d TO %d' % (OFF_K[0], OFF_K[-1]))
    s('T1', '1 T1 OFF')
    s('L2', 'TIMER RAMP  BEAM ON %d TO %d' % (ON_K_T1[0], ON_K_T1[-1]))
    s('T2', '2 T1 ON')
    s('L3', 'SHIFT REG  BEAM OFF %d TO %d' % (OFF_K[0], OFF_K[-1]))
    s('T3', '3 SR OFF')
    s('L4', 'SHIFT REG  BEAM ON %d TO %d' % (ON_K[0], ON_K[-1]))
    s('T4', '4 SR ON')
