"""make_updown_test.py - writes updown_test.asm ("UPDOWN TEST"): how the beam's up / down difference builds up.

Each page has five columns. In each column the beam is zeroed, moved to its start, and draws a short horizontal tick
there (the reference). Then, with the beam off, it moves up and back down the same distance N times
(N = 0 2 5 10 16, left to right, no zeroing in between) and draws a second tick where it ended. A beam that
goes up as far as it comes down puts both ticks on top of each other; the gap between them is what the up / down
difference left after N round trips. N = 0 is the control.

The pages (button 4 / joystick right: the next, button 1 / left: the one before) change one thing at a time:
  1  DAC $7F, scale $30: a short trip (~36 units) at full speed
  2  DAC $7F, scale $60: twice as far, at the same speed (twice the time)
  3  DAC $40, scale $C0: as far as page 2 at half the speed (four times page 1's time)
  4  DAC $7F, scale $60, down first and then up (page 2 the other way round: the sign)
  5, 6  page 2's trip low on the screen and high on it (where the beam is: the Full Grid's strokes reach far out)
  7, 8  page 2's distance at 3/4 and 7/8 of full speed (DAC $60, $70): how the difference grows between $40 and $7F
From pages 1 and 2 the error's growth with distance, from 2 and 3 whether it follows the distance or the time, from
the columns how it builds up and levels off over the round trips (the leak), from 4 its direction.
"""
from tc_common import *

CNT = 0xC884                          # the round trips left (RAM)
NS = (0, 2, 5, 10, 16)                # (every page within a 50 Hz frame, 30000 cycles: page 3 ~27000 - the owner photographs it)
XS = (-0x50, -0x28, 0x00, 0x28, 0x50)
PAGES = [  # (dac, scale, start y, label, text)
    (0x7F, 0x30, -0x40, 'T1', 'DAC 7F S30'),
    (0x7F, 0x60, -0x50, 'T2', 'DAC 7F S60'),
    (0x40, 0xC0, -0x50, 'T3', 'DAC 40 SC0'),
    (0x7F, 0x60, 0x50, 'T4', 'DOWN FIRST'),
    (0x7F, 0x60, -0x7F, 'T5', 'LOW'),          # (page 2's trip low on the screen: -127 .. -32)
    (0x7F, 0x60, 0x1C, 'T6', 'HIGH'),          # (and high: +28 .. +123)
    (0x60, 0x80, -0x50, 'T7', 'DAC 60 S80'),   # (page 2's distance at 3/4 speed)
    (0x70, 0x6D, -0x50, 'T8', 'DAC 70 S6D'),   # (.. at 7/8 speed)
]


def tick():
    """a 16 units wide tick to the right of where the beam is, and back"""
    w('        lda     #$10')
    w('        sta     <$04                ; scale $10: the tick')
    w('        ldd     #$007F')
    w('        jsr     Draw_Line_d')
    w('        ldd     #$0081')
    w('        jsr     Moveto_d')


def column(dac, scale, y0, x, n, tag):
    w('        jsr     Reset0Ref')
    w('        lda     #$7F')
    w('        jsr     Intensity_a')
    w('        lda     #$7F')
    w('        sta     <$04')
    w('        ldd     #$%02X%02X' % (b8(y0), b8(x)))
    w('        jsr     Moveto_d                ; the start')
    tick()                                                  # the reference
    if n:
        up = -dac if tag.startswith('4') else dac          # (page 4: down first)
        w('        lda     #$%02X' % scale)
        w('        sta     <$04')
        w('        lda     #%d' % n)
        w('        sta     $%04X' % CNT)
        w('L%s:' % tag)
        w('        ldd     #$%02X00' % b8(up))
        w('        jsr     Moveto_d')
        w('        ldd     #$%02X00' % b8(-up))
        w('        jsr     Moveto_d')
        w('        dec     $%04X' % CNT)
        w('        bne     L%s' % tag)
    tick()                                                  # where N round trips left the beam


def build():
    begin_paged('UPDOWN TEST', 'updown_test.asm - generated by make_updown_test.py: the beam up and down N times, a tick before and after; button 4 the next page.', len(PAGES))
    for p, (dac, scale, y0, label, txt) in enumerate(PAGES):
        ppage(p + 1)
        for i, (x, n) in enumerate(zip(XS, NS)):
            column(dac, scale, y0, x, n, '%d%d' % (p + 1, i))
        text(label, 0x70 if y0 < 0 else -0x70, -0x40)
        w('        lbra    Main')
    page_table(len(PAGES))
    w('')
    for p, (dac, scale, y0, label, txt) in enumerate(PAGES):
        string(label, '%d %s' % (p + 1, txt))
    finish('updown_test', 'Updown Test')


if __name__ == '__main__':
    build()
