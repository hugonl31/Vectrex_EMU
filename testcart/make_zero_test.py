"""make_zero_test.py - writes zero_test.asm: the zero reference's calibration value (the value primed into the
integrators' common zero reference, mux channel 1) as two programs do it, to photograph on a real Vectrex.
Buttons 1 / 2 (controller 1) pick the page.

  page 1  LAST HUMAN: Last Human's ZeroCal exactly (src/draw_lib.asm PosGo, cycle for cycle): the reference
          loaded with the value V, then a 4-cycle pulse of DAC -1 ($FF) before the multiplexer closes.
  page 2  UVMC2 SDK: the UVMC2 SDK's zero block (uvm2_draw.c uvm2_draw_reset, its bus capture: PCR=CC +7
          ORB=81 +1 ORA=00 +6 ORB=C0 +11 ORB=82 +1 ORA=V +7 ORA=FF +4 ORB=83 +6 PCR=CE), the cycles between the
          writes as measured.

Each page: 12 of Last Human's calibration squares (art.asm CalSquare: a 120-unit square traced 10 times with only
its horizontal edges lit, at Last Human's object scale $14), each after its own zero with V = 0, 1, 2, 3, 4, 6, 8,
12, 16, 24, 32, 35 (decimal, under it). With the right V for the console the ten passes fall on one another: two
crisp lines; the further off, the more the passes fan out (the beam drifts while it draws). Last Human's 6809
cartridge was checked at 2-3 on a real Vectrex; the SDK's own default is 35 ($23). In the emulator the two pages
need different V (Vectrex_EMU gives UVMC2 games a faster zero reference): the photos tell which is right.
"""
import os

VALS = [0, 1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 35]
COLS = [-0x60, -0x20, 0x20, 0x60]                 # (the squares' left edges, moves at scale $7F)
ROWS = [0x38, 0x00, -0x38]                         # (their top edges)
SQ_SCALE = 0x14                                    # (Last Human's OBJ_SCALE)

def b8(v):
    return v & 0xFF

A = []
w = A.append
def ws(lines):
    for s in lines: w(s)

w('; zero_test.asm - generated by make_zero_test.py: the zero reference calibration value, Last Human\'s')
w('; sequence (page 1) and the UVMC2 SDK\'s (page 2). Buttons 1 / 2 pick the page.')
w('; Build: lwasm --format=raw -o zero_test_raw.bin zero_test.asm, then pad to 32768 bytes with $FF.')
w('')
for name, adr in (('Wait_Recal', 0xF192), ('Read_Btns', 0xF1BA), ('Intensity_a', 0xF2AB), ('Moveto_d', 0xF312),
                  ('Reset0Ref', 0xF354), ('Print_Str_d', 0xF37A), ('Draw_VLp', 0xF410)):
    w('%-15s equ $%04X' % (name, adr))
w('Vec_Text_HW     equ $C82A')
w('Vec_Buttons     equ $C811')
w('Vec_0Ref_Enable equ $C824')
w('Page            equ $C880')
w('Cal             equ $C881')
w('')
w('        org     $0000')
w('        fcc     "g GCE 2026"')
w('        fcb     $80')
w('        fdb     $FD0D')
w('        fcb     $F8,$50,$20,-$40')
w('        fcc     "ZERO TEST"')
w('        fcb     $80')
w('        fcb     0')
w('')
w('Start:')
w('        clr     Page')
w('Main:')
w('        jsr     Wait_Recal')
w('        clr     Vec_0Ref_Enable         ; (Draw_VLp: no re-zero of its own after the list)')
w('        jsr     Read_Btns')
w('        lda     Vec_Buttons')
for k in range(2):
    w('        bita    #%d' % (1 << k))
    w('        beq     Bt%d' % k)
    w('        ldb     #%d' % k)
    w('        stb     Page')
    w('Bt%d' % k)
w('        lda     #$D0')
w('        tfr     a,dp')
w('        setdp   $D0')
w('        lda     Page')
w('        lbeq    Page1')
w('        lbra    Page2')
w('')

def label(lbl, y, x):
    ws(['        jsr     Reset0Ref', '        lda     #$7F', '        sta     <$04',
        '        ldu     #%s' % lbl, '        ldd     #$%02X%02X' % (b8(y), b8(x)), '        jsr     Print_Str_d'])

def labels(title):
    ws(['        lda     #$5F', '        jsr     Intensity_a', '        ldd     #$F830', '        std     Vec_Text_HW'])
    label(title, 0x6A, -0x50)
    for k, (v, (r, c)) in enumerate(zip(VALS, [(r, c) for r in ROWS for c in COLS])):
        label('V%d' % k, r - 0x22, c + 0x02)

def zero_lh():
    """Last Human's ZeroCal (draw_lib.asm PosGo), the value in Cal"""
    ws(['        ldb     #$CC',
        '        stb     <$0C                    ; CA2 low = ZERO the integrators, CB2 low = blank',
        '        clr     <$0A                    ; beam off',
        '        ldd     #$8100',
        '        std     <$00                    ; ORB = $81 (mux off), ORA = DAC 0',
        '        deca',
        '        sta     <$00                    ; mux on, select 0: Y sample/hold = 0',
        '        ldb     Cal',
        '        lda     #$82',
        '        std     <$00                    ; mux select 1 = zero reference, DAC = Cal',
        '        ldd     #$83FF',
        '        stb     <$01                    ; DAC = -1 (the fine-step discharge pulse)',
        '        sta     <$00                    ; mux off, select 1',
        '        brn     *',
        '        nop'])

def zero_sdk():
    """the UVMC2 SDK's zero block (uvm2_draw_reset): PCR=CC +7 ORB=81 +1 ORA=00 +6 ORB=C0 +11 ORB=82 +1 ORA=Cal +7
    ORA=FF +4 ORB=83 +6 PCR=CE (cycles from one write to the next; a store writes in its last cycle)"""
    ws(['        clr     <$0A                    ; beam off (the SDK blanks first)',
        '        lda     #$CC',
        '        sta     <$0C                    ; PCR = CC: clamp on',
        '        ldd     #$8100                  ; (+7: 3 + the std\'s 4th cycle)',
        '        std     <$00                    ; ORB = 81, ORA = 00 (+1)',
        '        lda     #$C0                    ; (+6)',
        '        sta     <$00                    ; ORB = C0: channel 0 (Y) primed inside the clamp',
        '        lda     #$82                    ; (+11: 2 + 5 + 4)',
        '        ldb     Cal',
        '        std     <$00                    ; ORB = 82, ORA = Cal (+1)',
        '        ldd     #$83FF                  ; (+7)',
        '        stb     <$01                    ; ORA = FF',
        '        sta     <$00                    ; ORB = 83 (+4): mux closed',
        '        lda     #$CE                    ; (+6)',
        '        sta     <$0C                    ; PCR = CE: clamp released'])

def square(k, v, y, x, zero):
    ws(['        lda     #%d' % v, '        sta     Cal'])
    zero()
    ws(['        lda     #$7F', '        sta     <$04',           # the move from the centre to the square's corner
        '        lda     #$%02X' % b8(y), '        sta     <$01', '        clr     <$00',
        '        lda     #$CE', '        sta     <$0C', '        clr     <$0A', '        inc     <$00',
        '        lda     #$%02X' % b8(x), '        sta     <$01', '        clr     <$05',
        '        lda     #$40',
        'Mv%s%d   bita    <$0D' % (zero.__name__[-3:], k), '        beq     Mv%s%d' % (zero.__name__[-3:], k),
        '        lda     #$%02X' % SQ_SCALE, '        sta     <$04',
        '        ldx     #CalSquare', '        jsr     Draw_VLp'])

for name, title, zero in (('Page1', 'TLH', zero_lh), ('Page2', 'TSDK', zero_sdk)):
    w(name + ':')
    labels(title)
    ws(['        lda     #$7F', '        jsr     Intensity_a'])
    for k, (v, (r, c)) in enumerate(zip(VALS, [(r, c) for r in ROWS for c in COLS])):
        square(k, v, r, c, zero)
    w('        jmp     Main')
    w('')

w('TLH     fcc     "LAST HUMAN ZERO"')
w('        fcb     $80')
w('TSDK    fcc     "UVMC2 SDK ZERO"')
w('        fcb     $80')
for k, v in enumerate(VALS):
    w('V%-6d fcc     "%02d"' % (k, v))
    w('        fcb     $80')
w('')
w('CalSquare                               ; Last Human\'s (art.asm): 10 passes, only the horizontal edges lit')
for _ in range(10):
    w('        fcb     $FF,$00,$78,$00,$88,$00,$FF,$00,$88,$00,$78,$00')
w('        fcb     $01')

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'zero_test.asm'), 'w', newline='\n').write('\n'.join(A) + '\n')
print('wrote zero_test.asm')
