"""make_pitrex_tiles_h.py - libretro/pitrex_tiles.h from icons/pitrex_cart.png and icons/pitrex_box.png: the PiTrex's
cartridge and box for the phone apps' library, written by them into system/vectrex_emu/thumbs at their start (the PC holds
the same two in src/frontend/pitrex_art.py - tools/make_pitrex_module.py). Run after the pictures change."""
import io, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
H = ["/* pitrex_tiles.h - generated by tools/make_pitrex_tiles_h.py from icons/pitrex_cart.png and icons/pitrex_box.png: the",
     " * PiTrex's cartridge and box for the library, written by the apps into system/vectrex_emu/thumbs. */",
     "#include <stdio.h>", "#include <string.h>"]
for nm, f in (('CART', 'pitrex_cart.png'), ('BOX', 'pitrex_box.png')):
    d = open(os.path.join(root, 'icons', f), 'rb').read()
    H.append("static const unsigned char VX_PITREX_%s[%d] = {" % (nm, len(d)))
    for i in range(0, len(d), 32):
        H.append("\t" + ",".join("%d" % b for b in d[i:i + 32]) + ",")
    H.append("};")
H += ["static void vx_pitrex_tile (const char *path, const unsigned char *d, size_t n)   /* (made unless it is there at this size) */",
      "{",
      "\tFILE *f = fopen (path, \"rb\"); if (f) { fseek (f, 0, SEEK_END); long have = ftell (f); fclose (f); if (have == (long) n) return; }",
      "\tf = fopen (path, \"wb\"); if (f) { fwrite (d, 1, n, f); fclose (f); }",
      "}",
      "/* thumbs: the folder system/vectrex_emu/thumbs - its carts and boxes folders must be there */",
      "static void vx_pitrex_tiles_write (const char *thumbs)",
      "{",
      "\tchar p[1024]; snprintf (p, sizeof p, \"%s/carts/PiTrex.png\", thumbs); vx_pitrex_tile (p, VX_PITREX_CART, sizeof VX_PITREX_CART);",
      "\tsnprintf (p, sizeof p, \"%s/boxes/PiTrex.png\", thumbs); vx_pitrex_tile (p, VX_PITREX_BOX, sizeof VX_PITREX_BOX);",
      "}", ""]
io.open(os.path.join(root, 'libretro', 'pitrex_tiles.h'), 'w', encoding='utf-8', newline='\n').write("\n".join(H))
print('wrote libretro/pitrex_tiles.h')
